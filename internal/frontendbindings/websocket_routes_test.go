package frontendbindings

import "testing"

func TestRenderWebsocketRoutesTS(t *testing.T) {
	// Keep the generated TS surface explicit so route ownership changes require
	// deliberate updates in the generator and callers.
	const expected = `// Code generated by ./scripts/go.sh run ./cmd/setta-gen-frontend-bindings -out frontend/src/utils/generatedGoRoutes.ts; DO NOT EDIT.
export const GoWebsocketRoutes = {
  frontend: "/ws/frontend",
  listenerById: "/ws/listeners/{listenerID}",
  terminalBySection: "/ws/terminals/{projectID}/{sectionID}",
} as const;
`

	if actual := RenderWebsocketRoutesTS(); actual != expected {
		t.Fatalf("unexpected websocket route bindings:\n%s", actual)
	}
}
