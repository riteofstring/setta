package frontendbindings

import "strings"

func RenderStatusEndpointsTS() string {
	var builder strings.Builder
	builder.WriteString("// Code generated by ./scripts/go.sh run ./cmd/setta-gen-frontend-bindings -endpoints-out frontend/src/utils/generatedGoEndpoints.ts; DO NOT EDIT.\n")
	builder.WriteString("import { get, type ResponseDataAndStatus } from \"./endpointUtils\";\n")
	builder.WriteString("import { GoHTTPRoutes } from \"./generatedGoRoutes\";\n\n")
	builder.WriteString("export type BackendInitEvent = {\n")
	builder.WriteString("  message: string;\n")
	builder.WriteString("  timestamp: string;\n")
	builder.WriteString("};\n\n")
	builder.WriteString("export type BackendInitStatusResponse = {\n")
	builder.WriteString("  events: Array<BackendInitEvent>;\n")
	builder.WriteString("  isReady: boolean;\n")
	builder.WriteString("  error: string | null;\n")
	builder.WriteString("  authCookieRefreshWindowSeconds: number;\n")
	builder.WriteString("  worktreeName: string | null;\n")
	builder.WriteString("};\n\n")
	builder.WriteString("export type AuthRefreshStatusResponse = {\n")
	builder.WriteString("  authCookieRefreshWindowSeconds: number;\n")
	builder.WriteString("};\n\n")
	builder.WriteString("export type ServerMode = \"ide\" | \"share\" | \"app\" | \"launcher\";\n\n")
	builder.WriteString("export type ServerModeResponse = {\n")
	builder.WriteString("  mode: ServerMode;\n")
	builder.WriteString("};\n\n")
	builder.WriteString("export type SettaHomeInfoResponse = {\n")
	builder.WriteString("  settaHome: string;\n")
	builder.WriteString("  globalSettaFilesBase: string;\n")
	builder.WriteString("  activeSettaFilesLocation: string | null;\n")
	builder.WriteString("  llmConfigPath: string;\n")
	builder.WriteString("};\n\n")
	builder.WriteString("export async function route_get_backend_init_status(): Promise<ResponseDataAndStatus<BackendInitStatusResponse>> {\n")
	builder.WriteString("  return await get(GoHTTPRoutes.getBackendInitStatus);\n")
	builder.WriteString("}\n\n")
	builder.WriteString("export async function route_get_auth_refresh_status(): Promise<ResponseDataAndStatus<AuthRefreshStatusResponse>> {\n")
	builder.WriteString("  return await get(GoHTTPRoutes.getAuthRefreshStatus);\n")
	builder.WriteString("}\n\n")
	builder.WriteString("export async function route_get_server_mode(): Promise<ResponseDataAndStatus<ServerModeResponse>> {\n")
	builder.WriteString("  return await get(GoHTTPRoutes.getServerMode);\n")
	builder.WriteString("}\n\n")
	builder.WriteString("export async function route_get_setta_home_info(): Promise<ResponseDataAndStatus<SettaHomeInfoResponse>> {\n")
	builder.WriteString("  return await get(GoHTTPRoutes.getSettaHomeInfo);\n")
	builder.WriteString("}\n")
	return builder.String()
}
