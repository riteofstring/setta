package frontendbindings

import (
	"fmt"
	"strings"

	"setta/internal/wsapi"
)

type WebsocketRoute struct {
	Name string
	Path string
}

func CurrentWebsocketRoutes() []WebsocketRoute {
	return []WebsocketRoute{
		{
			Name: "frontend",
			Path: wsapi.RouteFrontend,
		},
		{
			Name: "listenerById",
			Path: wsapi.RouteListenerByID,
		},
		{
			Name: "terminalBySection",
			Path: wsapi.RouteTerminalBySection,
		},
	}
}

func RenderWebsocketRoutesTS() string {
	var builder strings.Builder
	builder.WriteString("// Code generated by ./scripts/go.sh run ./cmd/setta-gen-frontend-bindings -out frontend/src/utils/generatedGoRoutes.ts; DO NOT EDIT.\n")
	builder.WriteString("export const GoWebsocketRoutes = {\n")
	for _, route := range CurrentWebsocketRoutes() {
		builder.WriteString(fmt.Sprintf("  %s: %q,\n", route.Name, route.Path))
	}
	builder.WriteString("} as const;\n")
	return builder.String()
}
