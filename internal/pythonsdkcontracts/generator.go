package pythonsdkcontracts

import (
	"fmt"
	"reflect"
	"sort"
	"strings"
)

// setta-go-type-discovery: skip
type GeneratedContracts struct {
	PythonModule string
}

type modelSpec struct {
	Name   string
	Fields []fieldSpec
}

type fieldSpec struct {
	Name        string
	TypeExpr    string
	DefaultExpr string
}

type generatedModuleSpec struct {
	Models          []modelSpec
	ExternalImports []string
	TypingImports   []string
	NeedsField      bool
}

type moduleImports struct {
	external   map[string]struct{}
	typing     map[string]struct{}
	needsField bool
}

func Build() (GeneratedContracts, error) {
	spec, err := buildGeneratedModuleSpec(currentContractTypes())
	if err != nil {
		return GeneratedContracts{}, err
	}
	return GeneratedContracts{PythonModule: renderPythonModule(spec)}, nil
}

func buildGeneratedModuleSpec(contractTypes []reflect.Type) (generatedModuleSpec, error) {
	models := make([]modelSpec, 0, len(contractTypes))
	imports := newModuleImports()
	for _, modelType := range contractTypes {
		model, err := buildModelSpec(modelType)
		if err != nil {
			return generatedModuleSpec{}, err
		}
		models = append(models, model)
		imports.collectFromModel(model)
		imports.collectFromType(modelType)
	}
	return generatedModuleSpec{
		Models:          models,
		ExternalImports: sortedImportNames(imports.external),
		TypingImports:   sortedImportNames(imports.typing),
		NeedsField:      imports.needsField,
	}, nil
}

func newModuleImports() moduleImports {
	return moduleImports{
		external: map[string]struct{}{},
		typing:   map[string]struct{}{},
	}
}

func (imports *moduleImports) collectFromModel(model modelSpec) {
	for _, field := range model.Fields {
		imports.collectFromField(field)
	}
}

func (imports *moduleImports) collectFromField(field fieldSpec) {
	if strings.Contains(field.TypeExpr, "Any") {
		imports.typing["Any"] = struct{}{}
	}
	if strings.Contains(field.TypeExpr, "Literal[") {
		imports.typing["Literal"] = struct{}{}
	}
	if strings.Contains(field.DefaultExpr, "Field(") {
		imports.needsField = true
	}
}

func (imports *moduleImports) collectFromType(modelType reflect.Type) {
	for _, field := range visibleFields(modelType) {
		if customImport := strings.TrimSpace(field.Tag.Get("py_import")); customImport != "" {
			imports.external[customImport] = struct{}{}
		}
	}
}

func renderPythonModule(spec generatedModuleSpec) string {
	var builder strings.Builder
	writeModuleHeader(&builder, spec)
	writeModelDeclarations(&builder, spec.Models)
	writeModuleExports(&builder, spec.Models)
	return builder.String()
}

func writeModuleHeader(builder *strings.Builder, spec generatedModuleSpec) {
	builder.WriteString("# Code generated by ./scripts/go.sh run ./cmd/setta-gen-python-sdk-contracts -out backend/setta/sdk_contracts/generated.py; DO NOT EDIT.\n\n")
	if len(spec.TypingImports) > 0 {
		builder.WriteString("from typing import ")
		builder.WriteString(strings.Join(spec.TypingImports, ", "))
		builder.WriteString("\n\n")
	}
	writePydanticImport(builder, spec.NeedsField)
	if len(spec.ExternalImports) == 0 {
		builder.WriteString("\n")
	} else {
		builder.WriteString("\n\n")
	}
	for _, line := range spec.ExternalImports {
		builder.WriteString(line)
		builder.WriteString("\n")
	}
	builder.WriteString("\n")
	builder.WriteString("SETTA_SDK_CONTRACT_VERSION = ")
	builder.WriteString(fmt.Sprintf("%d", SDKContractVersion))
	builder.WriteString("\n\n\n")
	builder.WriteString("class SettaSDKContractBaseModel(BaseModel):\n")
	builder.WriteString("    pass\n")
}

func writePydanticImport(builder *strings.Builder, needsField bool) {
	builder.WriteString("from pydantic import BaseModel")
	if needsField {
		builder.WriteString(", Field")
	}
	builder.WriteString("\n")
}

func writeModelDeclarations(builder *strings.Builder, models []modelSpec) {
	for _, model := range models {
		builder.WriteString("\n\n")
		writeModelDeclaration(builder, model)
	}
}

func writeModelDeclaration(builder *strings.Builder, model modelSpec) {
	builder.WriteString("class ")
	builder.WriteString(model.Name)
	builder.WriteString("(SettaSDKContractBaseModel):\n")
	if len(model.Fields) == 0 {
		builder.WriteString("    pass\n")
		return
	}
	for _, field := range model.Fields {
		builder.WriteString("    ")
		builder.WriteString(field.Name)
		builder.WriteString(": ")
		builder.WriteString(field.TypeExpr)
		if field.DefaultExpr != "" {
			builder.WriteString(" = ")
			builder.WriteString(field.DefaultExpr)
		}
		builder.WriteString("\n")
	}
}

func writeModuleExports(builder *strings.Builder, models []modelSpec) {
	builder.WriteString("\n\n")
	builder.WriteString("__all__ = [\n")
	builder.WriteString("    \"SETTA_SDK_CONTRACT_VERSION\",\n")
	for _, model := range models {
		builder.WriteString("    \"")
		builder.WriteString(model.Name)
		builder.WriteString("\",\n")
	}
	builder.WriteString("]\n")
}

func buildModelSpec(modelType reflect.Type) (modelSpec, error) {
	if modelType.Kind() != reflect.Struct {
		return modelSpec{}, fmt.Errorf("python sdk contracts: %s must be a struct", modelType)
	}
	spec := modelSpec{
		Name:   modelType.Name(),
		Fields: make([]fieldSpec, 0, modelType.NumField()),
	}
	for _, field := range visibleFields(modelType) {
		jsonName, err := fieldJSONName(field)
		if err != nil {
			return modelSpec{}, fmt.Errorf("python sdk contracts: %s.%s: %w", modelType.Name(), field.Name, err)
		}
		typeExpr, err := pythonTypeExpr(field.Type, strings.TrimSpace(field.Tag.Get("py_type")))
		if err != nil {
			return modelSpec{}, fmt.Errorf("python sdk contracts: %s.%s: %w", modelType.Name(), field.Name, err)
		}
		defaultExpr, err := pythonDefaultExpr(field, typeExpr)
		if err != nil {
			return modelSpec{}, fmt.Errorf("python sdk contracts: %s.%s: %w", modelType.Name(), field.Name, err)
		}
		spec.Fields = append(spec.Fields, fieldSpec{
			Name:        jsonName,
			TypeExpr:    typeExpr,
			DefaultExpr: defaultExpr,
		})
	}
	return spec, nil
}

func visibleFields(modelType reflect.Type) []reflect.StructField {
	fields := make([]reflect.StructField, 0, modelType.NumField())
	for index := 0; index < modelType.NumField(); index++ {
		field := modelType.Field(index)
		if !field.IsExported() {
			continue
		}
		if field.Tag.Get("json") == "-" {
			continue
		}
		fields = append(fields, field)
	}
	return fields
}

func fieldJSONName(field reflect.StructField) (string, error) {
	tag := strings.TrimSpace(field.Tag.Get("json"))
	if tag == "" {
		return "", fmt.Errorf("missing json tag")
	}
	name := strings.TrimSpace(strings.Split(tag, ",")[0])
	if name == "" {
		return "", fmt.Errorf("missing json field name")
	}
	return name, nil
}

func pythonTypeExpr(fieldType reflect.Type, override string) (string, error) {
	if overrideExpr := strings.TrimSpace(override); overrideExpr != "" {
		return overrideExpr, nil
	}
	if scalarExpr, ok := pythonScalarTypeExpr(fieldType); ok {
		return scalarExpr, nil
	}
	switch fieldType.Kind() {
	case reflect.Pointer:
		return pythonOptionalTypeExpr(fieldType.Elem())
	case reflect.Slice:
		return pythonSliceTypeExpr(fieldType)
	case reflect.Map:
		return pythonMapTypeExpr(fieldType)
	case reflect.Interface:
		return "Any", nil
	case reflect.Struct:
		return fieldType.Name(), nil
	default:
		return "", fmt.Errorf("unsupported type %s", fieldType)
	}
}

func pythonScalarTypeExpr(fieldType reflect.Type) (string, bool) {
	switch fieldType.Kind() {
	case reflect.String:
		return "str", true
	case reflect.Bool:
		return "bool", true
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return "int", true
	case reflect.Uint8:
		return "bytes", true
	case reflect.Uint, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return "int", true
	default:
		return "", false
	}
}

func pythonOptionalTypeExpr(elemType reflect.Type) (string, error) {
	elemExpr, err := pythonTypeExpr(elemType, "")
	if err != nil {
		return "", err
	}
	return elemExpr + " | None", nil
}

func pythonSliceTypeExpr(fieldType reflect.Type) (string, error) {
	if fieldType.Elem().Kind() == reflect.Uint8 {
		return "bytes", nil
	}
	elemExpr, err := pythonTypeExpr(fieldType.Elem(), "")
	if err != nil {
		return "", err
	}
	return "list[" + elemExpr + "]", nil
}

func pythonMapTypeExpr(fieldType reflect.Type) (string, error) {
	keyExpr, err := pythonTypeExpr(fieldType.Key(), "")
	if err != nil {
		return "", err
	}
	valueExpr, err := pythonTypeExpr(fieldType.Elem(), "")
	if err != nil {
		return "", err
	}
	return "dict[" + keyExpr + ", " + valueExpr + "]", nil
}

func pythonDefaultExpr(field reflect.StructField, typeExpr string) (string, error) {
	defaultTag := strings.TrimSpace(field.Tag.Get("py_default"))
	switch defaultTag {
	case "":
		if field.Type.Kind() == reflect.Pointer || strings.HasSuffix(typeExpr, " | None") {
			return "None", nil
		}
		return "", nil
	case "factory:list":
		return "Field(default_factory=list)", nil
	case "factory:dict":
		return "Field(default_factory=dict)", nil
	default:
		return defaultTag, nil
	}
}

func sortedImportNames(imports map[string]struct{}) []string {
	names := make([]string, 0, len(imports))
	for name := range imports {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}
