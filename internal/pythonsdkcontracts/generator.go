package pythonsdkcontracts

import (
	"fmt"
	"reflect"
	"sort"
	"strings"
)

type GeneratedContracts struct {
	PythonModule string
}

type modelSpec struct {
	Name   string
	Fields []fieldSpec
}

type fieldSpec struct {
	Name        string
	TypeExpr    string
	DefaultExpr string
}

func Build() (GeneratedContracts, error) {
	models := make([]modelSpec, 0, len(currentContractTypes()))
	externalImports := map[string]struct{}{}
	typingImports := map[string]struct{}{}
	needsField := false
	for _, modelType := range currentContractTypes() {
		model, err := buildModelSpec(modelType)
		if err != nil {
			return GeneratedContracts{}, err
		}
		models = append(models, model)
		for _, field := range model.Fields {
			if strings.Contains(field.TypeExpr, "Any") {
				typingImports["Any"] = struct{}{}
			}
			if strings.Contains(field.TypeExpr, "Literal[") {
				typingImports["Literal"] = struct{}{}
			}
			if strings.Contains(field.DefaultExpr, "Field(") {
				needsField = true
			}
		}
		for _, field := range visibleFields(modelType) {
			if customImport := strings.TrimSpace(field.Tag.Get("py_import")); customImport != "" {
				externalImports[customImport] = struct{}{}
			}
		}
	}

	var builder strings.Builder
	builder.WriteString("# Code generated by ./scripts/go.sh run ./cmd/setta-gen-python-sdk-contracts -out backend/setta/sdk_contracts/generated.py; DO NOT EDIT.\n")
	builder.WriteString("\n")
	if len(typingImports) > 0 {
		names := sortedImportNames(typingImports)
		builder.WriteString("from typing import ")
		builder.WriteString(strings.Join(names, ", "))
		builder.WriteString("\n")
		builder.WriteString("\n")
	}
	pydanticImports := []string{"BaseModel"}
	if needsField {
		pydanticImports = append(pydanticImports, "Field")
	}
	builder.WriteString("from pydantic import ")
	builder.WriteString(strings.Join(pydanticImports, ", "))
	builder.WriteString("\n")
	if len(externalImports) > 0 {
		builder.WriteString("\n")
	}
	for _, line := range sortedImportNames(externalImports) {
		builder.WriteString(renderImportLine(line))
		builder.WriteString("\n")
	}
	builder.WriteString("\n\n")
	builder.WriteString("SETTA_SDK_CONTRACT_VERSION = ")
	builder.WriteString(fmt.Sprintf("%d", SDKContractVersion))
	builder.WriteString("\n\n\n")
	builder.WriteString("class SettaSDKContractBaseModel(BaseModel):\n")
	builder.WriteString("    pass\n")
	for _, model := range models {
		builder.WriteString("\n\n")
		builder.WriteString("class ")
		builder.WriteString(model.Name)
		builder.WriteString("(SettaSDKContractBaseModel):\n")
		if len(model.Fields) == 0 {
			builder.WriteString("    pass\n")
			continue
		}
		for _, field := range model.Fields {
			renderedField := renderFieldLine(field)
			builder.WriteString(renderedField)
		}
	}
	builder.WriteString("\n\n")
	builder.WriteString("__all__ = [\n")
	builder.WriteString("    \"SETTA_SDK_CONTRACT_VERSION\",\n")
	for _, model := range models {
		builder.WriteString("    \"")
		builder.WriteString(model.Name)
		builder.WriteString("\",\n")
	}
	builder.WriteString("]\n")

	return GeneratedContracts{
		PythonModule: builder.String(),
	}, nil
}

func renderImportLine(line string) string {
	trimmed := strings.TrimSpace(line)
	if !strings.HasPrefix(trimmed, "from ") || !strings.Contains(trimmed, " import ") {
		return trimmed
	}
	module, names, ok := strings.Cut(strings.TrimPrefix(trimmed, "from "), " import ")
	if !ok {
		return trimmed
	}
	importNames := strings.Split(strings.TrimSpace(names), ",")
	cleanedNames := make([]string, 0, len(importNames))
	for _, name := range importNames {
		cleaned := strings.TrimSpace(name)
		if cleaned == "" {
			continue
		}
		cleanedNames = append(cleanedNames, cleaned)
	}
	if len(cleanedNames) == 0 {
		return trimmed
	}
	if len("from "+module+" import "+strings.Join(cleanedNames, ", ")) <= 88 {
		return "from " + module + " import " + strings.Join(cleanedNames, ", ")
	}
	var builder strings.Builder
	builder.WriteString("from ")
	builder.WriteString(module)
	builder.WriteString(" import (\n")
	for _, name := range cleanedNames {
		builder.WriteString("    ")
		builder.WriteString(name)
		builder.WriteString(",\n")
	}
	builder.WriteString(")")
	return builder.String()
}

func renderFieldLine(field fieldSpec) string {
	line := "    " + field.Name + ": " + field.TypeExpr
	if field.DefaultExpr == "" {
		return line + "\n"
	}
	if !strings.HasPrefix(field.DefaultExpr, "Field(") {
		return line + " = " + field.DefaultExpr + "\n"
	}
	oneLine := line + " = " + field.DefaultExpr
	if len(oneLine) <= 88 {
		return oneLine + "\n"
	}
	inner := strings.TrimSuffix(strings.TrimPrefix(field.DefaultExpr, "Field("), ")")
	return line + " = Field(\n        " + inner + "\n    )\n"
}

func buildModelSpec(modelType reflect.Type) (modelSpec, error) {
	if modelType.Kind() != reflect.Struct {
		return modelSpec{}, fmt.Errorf("python sdk contracts: %s must be a struct", modelType)
	}
	spec := modelSpec{
		Name:   modelType.Name(),
		Fields: make([]fieldSpec, 0, modelType.NumField()),
	}
	for _, field := range visibleFields(modelType) {
		jsonName, err := fieldJSONName(field)
		if err != nil {
			return modelSpec{}, fmt.Errorf("python sdk contracts: %s.%s: %w", modelType.Name(), field.Name, err)
		}
		typeExpr, err := pythonTypeExpr(field.Type, strings.TrimSpace(field.Tag.Get("py_type")))
		if err != nil {
			return modelSpec{}, fmt.Errorf("python sdk contracts: %s.%s: %w", modelType.Name(), field.Name, err)
		}
		defaultExpr, err := pythonDefaultExpr(field, typeExpr)
		if err != nil {
			return modelSpec{}, fmt.Errorf("python sdk contracts: %s.%s: %w", modelType.Name(), field.Name, err)
		}
		spec.Fields = append(spec.Fields, fieldSpec{
			Name:        jsonName,
			TypeExpr:    typeExpr,
			DefaultExpr: defaultExpr,
		})
	}
	return spec, nil
}

func visibleFields(modelType reflect.Type) []reflect.StructField {
	fields := make([]reflect.StructField, 0, modelType.NumField())
	for index := 0; index < modelType.NumField(); index++ {
		field := modelType.Field(index)
		if !field.IsExported() {
			continue
		}
		if field.Tag.Get("json") == "-" {
			continue
		}
		fields = append(fields, field)
	}
	return fields
}

func fieldJSONName(field reflect.StructField) (string, error) {
	tag := strings.TrimSpace(field.Tag.Get("json"))
	if tag == "" {
		return "", fmt.Errorf("missing json tag")
	}
	name := strings.TrimSpace(strings.Split(tag, ",")[0])
	if name == "" {
		return "", fmt.Errorf("missing json field name")
	}
	return name, nil
}

func pythonTypeExpr(fieldType reflect.Type, override string) (string, error) {
	if strings.TrimSpace(override) != "" {
		return strings.TrimSpace(override), nil
	}
	switch fieldType.Kind() {
	case reflect.String:
		return "str", nil
	case reflect.Bool:
		return "bool", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return "int", nil
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		if fieldType.Kind() == reflect.Uint8 {
			return "bytes", nil
		}
		return "int", nil
	case reflect.Pointer:
		elemExpr, err := pythonTypeExpr(fieldType.Elem(), "")
		if err != nil {
			return "", err
		}
		return elemExpr + " | None", nil
	case reflect.Slice:
		if fieldType.Elem().Kind() == reflect.Uint8 {
			return "bytes", nil
		}
		elemExpr, err := pythonTypeExpr(fieldType.Elem(), "")
		if err != nil {
			return "", err
		}
		return "list[" + elemExpr + "]", nil
	case reflect.Map:
		keyExpr, err := pythonTypeExpr(fieldType.Key(), "")
		if err != nil {
			return "", err
		}
		valueExpr, err := pythonTypeExpr(fieldType.Elem(), "")
		if err != nil {
			return "", err
		}
		return "dict[" + keyExpr + ", " + valueExpr + "]", nil
	case reflect.Interface:
		return "Any", nil
	case reflect.Struct:
		return fieldType.Name(), nil
	default:
		return "", fmt.Errorf("unsupported type %s", fieldType)
	}
}

func pythonDefaultExpr(field reflect.StructField, typeExpr string) (string, error) {
	defaultTag := strings.TrimSpace(field.Tag.Get("py_default"))
	switch defaultTag {
	case "":
		if field.Type.Kind() == reflect.Pointer || strings.HasSuffix(typeExpr, " | None") {
			return "None", nil
		}
		return "", nil
	case "factory:list":
		return "Field(default_factory=list)", nil
	case "factory:dict":
		return "Field(default_factory=dict)", nil
	default:
		return defaultTag, nil
	}
}

func sortedImportNames(imports map[string]struct{}) []string {
	names := make([]string, 0, len(imports))
	for name := range imports {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}
