package listenerendpoints

import (
	"fmt"
	"reflect"
	"sort"
	"strings"
)

const GeneratedPythonModulePath = "backend/setta/api/listener_endpoint_client.py"

type GeneratedPythonClient struct {
	PythonModule string
}

type pythonPayloadSpec struct {
	Name   string
	Fields []pythonPayloadFieldSpec
}

type pythonPayloadFieldSpec struct {
	Name     string
	TypeExpr string
}

type pythonEndpointMethodSpec struct {
	ConstantName          string
	EndpointName          string
	MethodName            string
	RequestName           string
	ResponseType          string
	ResponseValidationArg string
}

func BuildPythonClient() (GeneratedPythonClient, error) {
	importSet := map[string]struct{}{}
	payloads := make([]pythonPayloadSpec, 0, len(pythonClientEndpointSpecs))
	seenPayloads := map[string]struct{}{}
	endpoints := make([]pythonEndpointMethodSpec, 0, len(pythonClientEndpointSpecs))

	for _, spec := range pythonClientEndpointSpecs {
		requestName := spec.RequestType.Name()
		if _, ok := seenPayloads[requestName]; !ok {
			payload, payloadImports, err := buildPythonPayloadSpec(spec.RequestType)
			if err != nil {
				return GeneratedPythonClient{}, err
			}
			payloads = append(payloads, payload)
			seenPayloads[requestName] = struct{}{}
			for line := range payloadImports {
				importSet[line] = struct{}{}
			}
		}
		for _, line := range spec.ResponseImports {
			importSet[strings.TrimSpace(line)] = struct{}{}
		}
		endpoints = append(endpoints, pythonEndpointMethodSpec{
			ConstantName:          pythonEndpointConstantName(spec.EndpointName),
			EndpointName:          spec.EndpointName,
			MethodName:            spec.MethodName,
			RequestName:           requestName,
			ResponseType:          spec.ResponseType,
			ResponseValidationArg: pythonResponseValidationArg(spec.ResponseType),
		})
	}

	rendered := renderPythonClientModule(
		"# Code generated by ./scripts/go.sh run ./cmd/setta-gen-python-listener-endpoint-client -out "+GeneratedPythonModulePath+"; DO NOT EDIT.",
		sortedImportLines(importSet),
		payloads,
		endpoints,
	)
	return GeneratedPythonClient{PythonModule: rendered}, nil
}

func buildPythonPayloadSpec(requestType reflect.Type) (pythonPayloadSpec, map[string]struct{}, error) {
	if requestType.Kind() != reflect.Struct {
		return pythonPayloadSpec{}, nil, fmt.Errorf("python listener endpoint client: %s must be a struct", requestType)
	}
	fields := make([]pythonPayloadFieldSpec, 0, requestType.NumField())
	imports := map[string]struct{}{}
	for index := 0; index < requestType.NumField(); index++ {
		field := requestType.Field(index)
		if !field.IsExported() {
			continue
		}
		fieldSpec, fieldImports, err := buildPythonPayloadFieldSpec(field)
		if err != nil {
			return pythonPayloadSpec{}, nil, fmt.Errorf("python listener endpoint client: %s.%s: %w", requestType.Name(), field.Name, err)
		}
		fields = append(fields, fieldSpec)
		for line := range fieldImports {
			imports[line] = struct{}{}
		}
	}
	return pythonPayloadSpec{Name: requestType.Name(), Fields: fields}, imports, nil
}

func buildPythonPayloadFieldSpec(field reflect.StructField) (pythonPayloadFieldSpec, map[string]struct{}, error) {
	jsonName, omitempty, err := typedDictFieldJSONName(field)
	if err != nil {
		return pythonPayloadFieldSpec{}, nil, err
	}
	typeExpr, imports, err := typedDictFieldTypeExpr(field)
	if err != nil {
		return pythonPayloadFieldSpec{}, nil, err
	}
	if omitempty {
		typeExpr = "NotRequired[" + typeExpr + "]"
	}
	return pythonPayloadFieldSpec{Name: jsonName, TypeExpr: typeExpr}, imports, nil
}

func typedDictFieldJSONName(field reflect.StructField) (string, bool, error) {
	tag := strings.TrimSpace(field.Tag.Get("json"))
	if tag == "" {
		return "", false, fmt.Errorf("missing json tag")
	}
	parts := strings.Split(tag, ",")
	name := strings.TrimSpace(parts[0])
	if name == "" || name == "-" {
		return "", false, fmt.Errorf("missing json field name")
	}
	omitempty := false
	for _, option := range parts[1:] {
		if strings.TrimSpace(option) == "omitempty" {
			omitempty = true
		}
	}
	return name, omitempty, nil
}

func typedDictFieldTypeExpr(field reflect.StructField) (string, map[string]struct{}, error) {
	imports := map[string]struct{}{}
	if importTag := strings.TrimSpace(field.Tag.Get("py_import")); importTag != "" {
		for _, line := range strings.Split(importTag, "\n") {
			trimmed := strings.TrimSpace(line)
			if trimmed == "" {
				continue
			}
			imports[trimmed] = struct{}{}
		}
	}
	if override := strings.TrimSpace(field.Tag.Get("py_type")); override != "" {
		return override, imports, nil
	}
	typeExpr, err := inferPythonFieldTypeExpr(field.Type)
	if err != nil {
		return "", nil, err
	}
	if field.Type.Kind() == reflect.Pointer && !strings.Contains(typeExpr, " | None") && !fieldAllowsMissing(field) {
		typeExpr += " | None"
	}
	return typeExpr, imports, nil
}

func inferPythonFieldTypeExpr(fieldType reflect.Type) (string, error) {
	fieldType = unwrapPointerType(fieldType)
	if scalarExpr, ok := pythonScalarFieldTypeExpr(fieldType.Kind()); ok {
		return scalarExpr, nil
	}
	switch fieldType.Kind() {
	case reflect.Slice:
		return inferPythonListFieldTypeExpr(fieldType.Elem())
	case reflect.Map:
		return inferPythonMapFieldTypeExpr(fieldType)
	default:
		return "", fmt.Errorf("unsupported field type %s", fieldType)
	}
}

func unwrapPointerType(fieldType reflect.Type) reflect.Type {
	for fieldType.Kind() == reflect.Pointer {
		fieldType = fieldType.Elem()
	}
	return fieldType
}

func pythonScalarFieldTypeExpr(kind reflect.Kind) (string, bool) {
	switch kind {
	case reflect.String:
		return "str", true
	case reflect.Bool:
		return "bool", true
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return "int", true
	case reflect.Uint, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return "int", true
	case reflect.Uint8:
		return "bytes", true
	case reflect.Interface:
		return "object", true
	default:
		return "", false
	}
}

func inferPythonListFieldTypeExpr(elementType reflect.Type) (string, error) {
	elementExpr, err := inferPythonFieldTypeExpr(elementType)
	if err != nil {
		return "", err
	}
	return "list[" + elementExpr + "]", nil
}

func inferPythonMapFieldTypeExpr(fieldType reflect.Type) (string, error) {
	keyExpr, err := inferPythonFieldTypeExpr(fieldType.Key())
	if err != nil {
		return "", err
	}
	valueExpr, err := inferPythonFieldTypeExpr(fieldType.Elem())
	if err != nil {
		return "", err
	}
	return "dict[" + keyExpr + ", " + valueExpr + "]", nil
}

func fieldAllowsMissing(field reflect.StructField) bool {
	_, omitempty, err := typedDictFieldJSONName(field)
	return err == nil && omitempty
}

func sortedImportLines(imports map[string]struct{}) []string {
	lines := make([]string, 0, len(imports))
	for line := range imports {
		if strings.TrimSpace(line) == "" {
			continue
		}
		lines = append(lines, line)
	}
	sort.Strings(lines)
	return lines
}

func pythonEndpointConstantName(endpointName string) string {
	trimmed := strings.TrimSpace(strings.TrimPrefix(endpointName, "route_"))
	parts := strings.Split(trimmed, "_")
	upperParts := make([]string, 0, len(parts))
	for _, part := range parts {
		part = strings.TrimSpace(part)
		if part == "" {
			continue
		}
		upperParts = append(upperParts, strings.ToUpper(part))
	}
	return "ROUTER_ENDPOINT_" + strings.Join(upperParts, "_")
}

func pythonResponseValidationArg(responseType string) string {
	trimmed := strings.TrimSpace(responseType)
	if trimmed == "None" {
		return "type(None)"
	}
	return trimmed
}

func renderPythonClientModule(
	generatedHeader string,
	importLines []string,
	payloads []pythonPayloadSpec,
	endpoints []pythonEndpointMethodSpec,
) string {
	var builder strings.Builder
	builder.WriteString(generatedHeader)
	builder.WriteString("\n\n")
	builder.WriteString("from typing import Awaitable, Callable, NotRequired, TypedDict\n")
	builder.WriteString("from pydantic import TypeAdapter\n")
	if len(importLines) > 0 {
		builder.WriteString("\n")
		for _, line := range importLines {
			builder.WriteString(line)
			builder.WriteString("\n")
		}
	}
	builder.WriteString("\n")
	builder.WriteString("ListenerEndpointCaller = Callable[[str, object], Awaitable[object]]\n")
	if len(endpoints) > 0 {
		builder.WriteString("\n")
		for _, endpoint := range endpoints {
			builder.WriteString(endpoint.ConstantName)
			builder.WriteString(` = "`)
			builder.WriteString(endpoint.EndpointName)
			builder.WriteString("\"\n")
		}
	}
	for _, payload := range payloads {
		builder.WriteString("\n\n")
		writePythonPayloadSpec(&builder, payload)
	}
	builder.WriteString("\n\n\n")
	builder.WriteString("class RouterEndpointAPI:\n")
	builder.WriteString("    \"\"\"Thin Python client for the active Go-owned listener endpoint set.\"\"\"\n\n")
	builder.WriteString("    def __init__(self, caller: ListenerEndpointCaller) -> None:\n")
	builder.WriteString("        self._caller = caller\n")
	for _, endpoint := range endpoints {
		builder.WriteString("\n\n")
		writePythonEndpointMethod(&builder, endpoint)
	}
	builder.WriteString("\n")
	return builder.String()
}

func writePythonPayloadSpec(builder *strings.Builder, payload pythonPayloadSpec) {
	builder.WriteString("class ")
	builder.WriteString(payload.Name)
	builder.WriteString("(TypedDict):\n")
	if len(payload.Fields) == 0 {
		builder.WriteString("    pass\n")
		return
	}
	for _, field := range payload.Fields {
		builder.WriteString("    ")
		builder.WriteString(field.Name)
		builder.WriteString(": ")
		builder.WriteString(field.TypeExpr)
		builder.WriteString("\n")
	}
}

func writePythonEndpointMethod(builder *strings.Builder, endpoint pythonEndpointMethodSpec) {
	builder.WriteString("    async def ")
	builder.WriteString(endpoint.MethodName)
	builder.WriteString("(self, payload: ")
	builder.WriteString(endpoint.RequestName)
	builder.WriteString(") -> ")
	builder.WriteString(endpoint.ResponseType)
	builder.WriteString(":\n")
	builder.WriteString("        return TypeAdapter(")
	builder.WriteString(endpoint.ResponseValidationArg)
	builder.WriteString(").validate_python(await self._caller(")
	builder.WriteString(endpoint.ConstantName)
	builder.WriteString(", payload))\n")
}
