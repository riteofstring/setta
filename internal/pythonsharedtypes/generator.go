package pythonsharedtypes

import (
	"encoding/json"
	"fmt"
	"reflect"
	"sort"
	"strconv"
	"strings"

	"setta/internal/sharedtypes"
)

type GeneratedTypes struct {
	PythonModule string
}

const generatedPythonSharedTypesImportPrefix = "from setta.types.generated.go_shared_types import "

type fieldSpec struct {
	Name        string
	TypeExpr    string
	DefaultExpr string
}

func Build() (GeneratedTypes, error) {
	sidecar, err := sharedtypes.BuildSemanticSidecar()
	if err != nil {
		return GeneratedTypes{}, err
	}
	defaultSources, err := defaultSourcesFromSidecar(
		sidecar,
		sharedtypes.DefaultProfilePythonShared,
		sharedtypes.DefaultProfileFrontend,
	)
	if err != nil {
		return GeneratedTypes{}, err
	}

	standardBlocks, standardImports, err := pythonSharedSchemaDeclarations(
		defaultSources,
	)
	if err != nil {
		return GeneratedTypes{}, err
	}

	return GeneratedTypes{
		PythonModule: renderGeneratedTypesModule(standardImports, standardBlocks),
	}, nil
}

func renderGeneratedTypesModule(
	importLines []string,
	blocks []string,
) string {
	var builder strings.Builder
	builder.WriteString("# Code generated by ./scripts/go.sh run ./cmd/setta-gen-python-shared-types -out backend/setta/types/generated/go_shared_types.py; DO NOT EDIT.\n")
	builder.WriteString("\n")
	builder.WriteString("from __future__ import annotations\n")
	builder.WriteString("\n")
	for _, line := range importLines {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" {
			continue
		}
		builder.WriteString(trimmed)
		builder.WriteString("\n")
	}
	builder.WriteString("\n")
	for _, block := range blocks {
		trimmed := strings.TrimSpace(block)
		if trimmed == "" {
			continue
		}
		builder.WriteString(trimmed)
		builder.WriteString("\n\n")
	}
	return builder.String()
}

func buildModelFieldSpec(
	contractName string,
	ownerType reflect.Type,
	field reflect.StructField,
	currentTypeExpr string,
	defaultSourcesByType map[reflect.Type]reflect.Value,
) (fieldSpec, map[string]struct{}, error) {
	jsonName, err := fieldJSONName(field)
	if err != nil {
		return fieldSpec{}, nil, fmt.Errorf(
			"python shared types: %s.%s: %w",
			contractName,
			field.Name,
			err,
		)
	}
	typeExpr, fieldImports, err := pythonPatchedFieldTypeExpr(
		field,
		currentTypeExpr,
	)
	if err != nil {
		return fieldSpec{}, nil, fmt.Errorf(
			"python shared types: %s.%s: %w",
			contractName,
			field.Name,
			err,
		)
	}

	defaultExpr, defaultImports, err := pythonPatchedFieldDefaultExpr(
		ownerType,
		field,
		typeExpr,
		defaultSourcesByType,
	)
	if err != nil {
		return fieldSpec{}, nil, fmt.Errorf(
			"python shared types: %s.%s: %w",
			contractName,
			field.Name,
			err,
		)
	}
	mergeImportSet(fieldImports, defaultImports)
	if field.Type.Kind() == reflect.Pointer && !strings.Contains(typeExpr, " | None") {
		typeExpr += " | None"
	}

	return fieldSpec{
		Name:        jsonName,
		TypeExpr:    typeExpr,
		DefaultExpr: defaultExpr,
	}, fieldImports, nil
}

func mergeImportSet(dst map[string]struct{}, src map[string]struct{}) {
	if dst == nil {
		return
	}
	for line := range src {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" {
			continue
		}
		dst[trimmed] = struct{}{}
	}
}

func fieldJSONName(field reflect.StructField) (string, error) {
	tag := strings.TrimSpace(field.Tag.Get("json"))
	if tag == "" {
		return "", fmt.Errorf("missing json tag")
	}
	name := strings.TrimSpace(strings.Split(tag, ",")[0])
	if name == "" {
		return "", fmt.Errorf("missing json field name")
	}
	return name, nil
}

func pythonPatchedFieldTypeExpr(
	field reflect.StructField,
	currentTypeExpr string,
) (string, map[string]struct{}, error) {
	imports := map[string]struct{}{}
	importTag := strings.TrimSpace(field.Tag.Get("py_import"))
	if importTag != "" {
		for _, line := range strings.Split(importTag, "\n") {
			trimmed := strings.TrimSpace(line)
			if trimmed == "" || strings.HasPrefix(trimmed, generatedPythonSharedTypesImportPrefix) {
				continue
			}
			imports[trimmed] = struct{}{}
		}
	}
	override := strings.TrimSpace(field.Tag.Get("py_type"))
	if override != "" {
		return override, imports, nil
	}
	currentTypeExpr = strings.TrimSpace(currentTypeExpr)
	if currentTypeExpr == "" {
		return "", nil, fmt.Errorf("missing datamodel type expression")
	}
	return currentTypeExpr, imports, nil
}

func pythonPatchedFieldDefaultExpr(
	ownerType reflect.Type,
	field reflect.StructField,
	typeExpr string,
	defaultSourcesByType map[reflect.Type]reflect.Value,
) (string, map[string]struct{}, error) {
	defaultTag := strings.TrimSpace(field.Tag.Get("py_default"))
	switch defaultTag {
	case "":
		if field.Type.Kind() == reflect.Pointer || strings.HasSuffix(typeExpr, " | None") {
			return "None", nil, nil
		}
		return "", nil, nil
	case "go_value":
		return pythonGoValueDefaultExpr(ownerType, field, typeExpr, defaultSourcesByType)
	case "factory:list":
		return "Field(default_factory=list)", nil, nil
	case "factory:dict":
		return "Field(default_factory=dict)", nil, nil
	default:
		return defaultTag, nil, nil
	}
}

func pythonGoValueDefaultExpr(
	ownerType reflect.Type,
	field reflect.StructField,
	typeExpr string,
	defaultSourcesByType map[reflect.Type]reflect.Value,
) (string, map[string]struct{}, error) {
	defaultValue, ok := pythonSharedDefaultValueForField(ownerType, field, defaultSourcesByType)
	if !ok {
		defaultValue = reflect.Zero(field.Type)
	}
	for defaultValue.IsValid() && defaultValue.Kind() == reflect.Interface {
		if defaultValue.IsNil() {
			return "None", nil, nil
		}
		defaultValue = defaultValue.Elem()
	}
	for defaultValue.IsValid() && defaultValue.Kind() == reflect.Pointer {
		if defaultValue.IsNil() {
			return "None", nil, nil
		}
		defaultValue = defaultValue.Elem()
	}
	if !defaultValue.IsValid() {
		return "None", nil, nil
	}
	if expr, ok := pythonEmptyCollectionDefaultExpr(defaultValue); ok {
		return expr, nil, nil
	}
	if expr, ok := pythonScalarDefaultExpr(defaultValue); ok {
		return expr, nil, nil
	}
	payload, err := json.Marshal(defaultValue.Interface())
	if err != nil {
		return "", nil, err
	}
	return fmt.Sprintf(
		"Field(default_factory=lambda: TypeAdapter(%s).validate_json(%q))",
		strings.TrimSpace(typeExpr),
		string(payload),
	), map[string]struct{}{"from pydantic import TypeAdapter": {}}, nil
}

func pythonEmptyCollectionDefaultExpr(value reflect.Value) (string, bool) {
	switch value.Kind() {
	case reflect.Map:
		if value.IsNil() || value.Len() == 0 {
			return "Field(default_factory=dict)", true
		}
	case reflect.Slice:
		if value.Type().Elem().Kind() == reflect.Uint8 {
			return "", false
		}
		if value.IsNil() || value.Len() == 0 {
			return "Field(default_factory=list)", true
		}
	}
	return "", false
}

func pythonScalarDefaultExpr(value reflect.Value) (string, bool) {
	valueType := value.Type()
	if valueType.Kind() == reflect.String && valueType.Name() != "" && valueType.PkgPath() != "" {
		return "", false
	}
	switch value.Kind() {
	case reflect.String:
		return strconv.Quote(value.String()), true
	case reflect.Bool:
		if value.Bool() {
			return "True", true
		}
		return "False", true
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return strconv.FormatInt(value.Int(), 10), true
	case reflect.Uint, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr:
		return strconv.FormatUint(value.Uint(), 10), true
	case reflect.Uint8:
		return strconv.FormatUint(value.Uint(), 10), true
	case reflect.Float32:
		return pythonFloatLiteral(value.Float(), 32), true
	case reflect.Float64:
		return pythonFloatLiteral(value.Float(), 64), true
	default:
		return "", false
	}
}

func pythonFloatLiteral(value float64, bitSize int) string {
	literal := strconv.FormatFloat(value, 'f', -1, bitSize)
	if strings.ContainsRune(literal, '.') {
		return literal
	}
	return literal + ".0"
}

func renderFieldLine(field fieldSpec) string {
	line := "    " + field.Name + ": " + field.TypeExpr
	if field.DefaultExpr == "" {
		return line + "\n"
	}
	return line + " = " + field.DefaultExpr + "\n"
}

func sortedImportNames(imports map[string]struct{}) []string {
	names := make([]string, 0, len(imports))
	for name := range imports {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}
