package pythonsharedtypes

import (
	"fmt"
	"reflect"
	"sort"
	"strings"

	"setta/internal/stringenumvalues"
)

type GeneratedTypes struct {
	PythonModule string
}

type modelSpec struct {
	Name   string
	Fields []fieldSpec
}

type fieldSpec struct {
	Name        string
	TypeExpr    string
	DefaultExpr string
}

func Build() (GeneratedTypes, error) {
	specs, err := currentContractSpecs()
	if err != nil {
		return GeneratedTypes{}, err
	}
	models := make([]modelSpec, 0, len(specs))
	enums := make([]contractSpec, 0, len(specs))
	typingImports := map[string]struct{}{}
	needsEnum := false

	for _, spec := range specs {
		switch spec.Kind {
		case contractKindEnum:
			if len(spec.EnumValues) == 0 {
				enumValues, ok, err := resolveEnumValues(spec)
				if err != nil {
					return GeneratedTypes{}, err
				}
				if !ok {
					return GeneratedTypes{}, fmt.Errorf(
						"python shared types: enum %s has no values",
						spec.Name,
					)
				}
				spec.EnumValues = enumValues
			}
			needsEnum = true
			enums = append(enums, spec)
		case contractKindModel:
			model, err := buildModelSpec(spec)
			if err != nil {
				return GeneratedTypes{}, err
			}
			models = append(models, model)
			for _, field := range model.Fields {
				if strings.Contains(field.TypeExpr, "Any") {
					typingImports["Any"] = struct{}{}
				}
			}
		default:
			return GeneratedTypes{}, fmt.Errorf(
				"python shared types: unsupported contract kind %q",
				spec.Kind,
			)
		}
	}

	var builder strings.Builder
	builder.WriteString("# Code generated by ./scripts/go.sh run ./cmd/setta-gen-python-shared-types -out backend/setta/types/generated/go_shared_types.py; DO NOT EDIT.\n")
	builder.WriteString("\n")
	if needsEnum {
		builder.WriteString("from enum import Enum\n")
	}
	if len(typingImports) > 0 {
		builder.WriteString("from typing import ")
		builder.WriteString(strings.Join(sortedImportNames(typingImports), ", "))
		builder.WriteString("\n")
	}
	if needsEnum || len(typingImports) > 0 {
		builder.WriteString("\n")
	}
	builder.WriteString("from pydantic import BaseModel, ConfigDict\n")
	builder.WriteString("\n\n")
	builder.WriteString("class SettaSharedTypeModel(BaseModel):\n")
	builder.WriteString("    model_config = ConfigDict(extra=\"forbid\")\n")

	for _, enumSpec := range enums {
		builder.WriteString("\n\n")
		builder.WriteString("class ")
		builder.WriteString(enumSpec.Name)
		builder.WriteString("(str, Enum):\n")
		for _, value := range enumSpec.EnumValues {
			builder.WriteString("    ")
			builder.WriteString(value.Name)
			builder.WriteString(" = ")
			builder.WriteString(fmt.Sprintf("%q", value.Value))
			builder.WriteString("\n")
		}
	}

	for _, model := range models {
		builder.WriteString("\n\n")
		builder.WriteString("class ")
		builder.WriteString(model.Name)
		builder.WriteString("(SettaSharedTypeModel):\n")
		for _, field := range model.Fields {
			builder.WriteString(renderFieldLine(field))
		}
	}

	return GeneratedTypes{PythonModule: builder.String()}, nil
}

func resolveEnumValues(spec contractSpec) ([]enumValueSpec, bool, error) {
	if spec.Type == nil {
		return nil, false, nil
	}
	values, ok, err := stringenumvalues.Default().Values(spec.Type)
	if err != nil {
		return nil, false, err
	}
	if !ok {
		return nil, false, nil
	}
	resolved := make([]enumValueSpec, 0, len(values))
	for _, value := range values {
		resolved = append(resolved, enumValueSpec{
			Name:  value.Name,
			Value: value.Value,
		})
	}
	return resolved, true, nil
}

func buildModelSpec(spec contractSpec) (modelSpec, error) {
	modelType := spec.Type
	if modelType.Kind() != reflect.Struct {
		return modelSpec{}, fmt.Errorf("python shared types: %s must be a struct", modelType)
	}
	model := modelSpec{
		Name:   spec.Name,
		Fields: make([]fieldSpec, 0, modelType.NumField()),
	}
	for _, field := range visibleFields(modelType) {
		jsonName, err := fieldJSONName(field)
		if err != nil {
			return modelSpec{}, fmt.Errorf(
				"python shared types: %s.%s: %w",
				spec.Name,
				field.Name,
				err,
			)
		}
		typeExpr, err := pythonTypeExpr(field.Type, strings.TrimSpace(field.Tag.Get("py_type")))
		if err != nil {
			return modelSpec{}, fmt.Errorf(
				"python shared types: %s.%s: %w",
				spec.Name,
				field.Name,
				err,
			)
		}
		defaultExpr, err := pythonDefaultExpr(field, typeExpr, spec.FieldDefaults)
		if err != nil {
			return modelSpec{}, fmt.Errorf(
				"python shared types: %s.%s: %w",
				spec.Name,
				field.Name,
				err,
			)
		}
		model.Fields = append(model.Fields, fieldSpec{
			Name:        jsonName,
			TypeExpr:    typeExpr,
			DefaultExpr: defaultExpr,
		})
	}
	return model, nil
}

func visibleFields(modelType reflect.Type) []reflect.StructField {
	fields := make([]reflect.StructField, 0, modelType.NumField())
	for index := 0; index < modelType.NumField(); index++ {
		field := modelType.Field(index)
		if !field.IsExported() {
			continue
		}
		if field.Tag.Get("json") == "-" {
			continue
		}
		fields = append(fields, field)
	}
	return fields
}

func fieldJSONName(field reflect.StructField) (string, error) {
	tag := strings.TrimSpace(field.Tag.Get("json"))
	if tag == "" {
		return "", fmt.Errorf("missing json tag")
	}
	name := strings.TrimSpace(strings.Split(tag, ",")[0])
	if name == "" {
		return "", fmt.Errorf("missing json field name")
	}
	return name, nil
}

func pythonTypeExpr(fieldType reflect.Type, override string) (string, error) {
	if strings.TrimSpace(override) != "" {
		return strings.TrimSpace(override), nil
	}
	switch fieldType.Kind() {
	case reflect.String:
		return "str", nil
	case reflect.Bool:
		return "bool", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return "int", nil
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		if fieldType.Kind() == reflect.Uint8 {
			return "bytes", nil
		}
		return "int", nil
	case reflect.Pointer:
		elemExpr, err := pythonTypeExpr(fieldType.Elem(), "")
		if err != nil {
			return "", err
		}
		return elemExpr + " | None", nil
	case reflect.Slice:
		if fieldType.Elem().Kind() == reflect.Uint8 {
			return "bytes", nil
		}
		elemExpr, err := pythonTypeExpr(fieldType.Elem(), "")
		if err != nil {
			return "", err
		}
		return "list[" + elemExpr + "]", nil
	case reflect.Map:
		keyExpr, err := pythonTypeExpr(fieldType.Key(), "")
		if err != nil {
			return "", err
		}
		valueExpr, err := pythonTypeExpr(fieldType.Elem(), "")
		if err != nil {
			return "", err
		}
		return "dict[" + keyExpr + ", " + valueExpr + "]", nil
	case reflect.Interface:
		return "Any", nil
	case reflect.Struct:
		return fieldType.Name(), nil
	default:
		return "", fmt.Errorf("unsupported type %s", fieldType)
	}
}

func pythonDefaultExpr(
	field reflect.StructField,
	typeExpr string,
	overrides map[string]string,
) (string, error) {
	jsonName, err := fieldJSONName(field)
	if err != nil {
		return "", err
	}
	if override, ok := overrides[jsonName]; ok {
		return override, nil
	}
	defaultTag := strings.TrimSpace(field.Tag.Get("py_default"))
	switch defaultTag {
	case "":
		if field.Type.Kind() == reflect.Pointer || strings.HasSuffix(typeExpr, " | None") {
			return "None", nil
		}
		return "", nil
	case "factory:list":
		return "Field(default_factory=list)", nil
	case "factory:dict":
		return "Field(default_factory=dict)", nil
	default:
		return defaultTag, nil
	}
}

func renderFieldLine(field fieldSpec) string {
	line := "    " + field.Name + ": " + field.TypeExpr
	if field.DefaultExpr == "" {
		return line + "\n"
	}
	return line + " = " + field.DefaultExpr + "\n"
}

func sortedImportNames(imports map[string]struct{}) []string {
	names := make([]string, 0, len(imports))
	for name := range imports {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}
