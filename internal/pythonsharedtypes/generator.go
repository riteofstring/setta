func Build() (GeneratedTypes, error) {
	ctx, err := buildGenerationContext()
	if err != nil {
		return GeneratedTypes{}, err
	}

	standardBlocks, standardImports, standardDeclarationNames, err := pythonSharedSchemaDeclarations(
		ctx.DefaultSourcesByType,
	)
	if err != nil {
		return GeneratedTypes{}, err
	}

	standardImports = appendUniqueImportLines(
		standardImports,
		pythonBlockImportLines(standardBlocks)...,
	)
	standardImports = appendUniqueImportLines(
		standardImports,
		pythonRouteEnumImportLines(ctx.Sidecar, standardDeclarationNames)...,
	)
	standardBlocks = append(
		standardBlocks,
		pythonRouteEnumBlocks(ctx.Sidecar, standardDeclarationNames)...,
	)

	return GeneratedTypes{
		PythonModule: renderGeneratedTypesModule(standardImports, standardBlocks),
	}, nil
}

func pythonModelRequiresStandardFieldPatch(t reflect.Type) bool {
	if t == nil || t.Kind() != reflect.Struct {
		return false
	}
	for _, field := range visibleFields(t) {
		if pythonFieldRequiresStandardFieldPatch(field) {
			return true
		}
	}
	return false
}

func pythonFieldRequiresStandardFieldPatch(field reflect.StructField) bool {
	if strings.TrimSpace(field.Tag.Get("py_type")) != "" {
		return true
	}
	if strings.TrimSpace(field.Tag.Get("py_import")) != "" {
		return true
	}
	return false
}

func renderGeneratedTypesModule(
	importLines []string,
	blocks []string,
) string {
	var builder strings.Builder
	builder.WriteString("# Code generated by ./scripts/go.sh run ./cmd/setta-gen-python-shared-types -out backend/setta/types/generated/go_shared_types.py; DO NOT EDIT.\n")
	builder.WriteString("\n")
	builder.WriteString("from __future__ import annotations\n")
	builder.WriteString("\n")
	writeRawImportLines(&builder, importLines)
	writeStandardSchemaBlocks(&builder, blocks)
	return builder.String()
}

func writeRawImportLines(builder *strings.Builder, importLines []string) {
	if len(importLines) == 0 {
		return
	}
	for _, line := range importLines {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" {
			continue
		}
		builder.WriteString(trimmed)
		builder.WriteString("\n")
	}
	builder.WriteString("\n")
}

func writeStandardSchemaBlocks(builder *strings.Builder, blocks []string) {
	for _, block := range blocks {
		trimmed := strings.TrimSpace(block)
		if trimmed == "" {
			continue
		}
		builder.WriteString(trimmed)
		builder.WriteString("\n\n")
	}
}

func appendUniqueImportLines(base []string, extras ...string) []string {
	out := append([]string(nil), base...)
	seen := map[string]struct{}{}
	for _, line := range out {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" {
			continue
		}
		seen[trimmed] = struct{}{}
	}
	for _, line := range extras {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" {
			continue
		}
		if _, exists := seen[trimmed]; exists {
			continue
		}
		seen[trimmed] = struct{}{}
		out = append(out, trimmed)
	}
	return out
}

func pythonBlockImportLines(blocks []string) []string {
	imports := map[string]struct{}{}
	for _, block := range blocks {
		for _, name := range referencedTypeNames(block) {
			if name == "datetime" {
				imports["from datetime import datetime"] = struct{}{}
				break
			}
		}
		if strings.Contains(block, "TypeAdapter(") {
			imports["from pydantic import TypeAdapter"] = struct{}{}
		}
	}
	return sortedImportNames(imports)
}

func pythonRouteEnumImportLines(
	sidecar sharedtypes.SemanticSidecar,
	standardDeclarationNames map[string]struct{},
) []string {
	if len(pythonRouteEnumBlocks(sidecar, standardDeclarationNames)) == 0 {
		return nil
	}
	return []string{"from enum import Enum"}
}

func pythonRouteEnumBlocks(
	sidecar sharedtypes.SemanticSidecar,
	standardDeclarationNames map[string]struct{},
) []string {
	if len(sidecar.Routes) == 0 {
		return nil
	}
	if _, present := standardDeclarationNames["Route"]; present {
		return nil
	}

	var builder strings.Builder
	builder.WriteString("class Route(str, Enum):\n")
	for _, route := range sidecar.Routes {
		name := strings.TrimSpace(route.Name)
		if name == "" {
			continue
		}
		builder.WriteString("    ")
		builder.WriteString(name)
		builder.WriteString(" = ")
		builder.WriteString(fmt.Sprintf("%q", route.Path))
		builder.WriteString("\n")
	}
	return []string{builder.String()}
}

func buildModelFieldSpec(
	contractName string,
	ownerType reflect.Type,
	field reflect.StructField,
	knownContractNames map[string]struct{},
	defaultSourcesByType map[reflect.Type]reflect.Value,
) (fieldSpec, map[string]struct{}, error) {
	jsonName, err := fieldJSONName(field)
	if err != nil {
		return fieldSpec{}, nil, fmt.Errorf(
			"python shared types: %s.%s: %w",
			contractName,
			field.Name,
			err,
		)
	}
	typeSpec, err := pythonFieldTypeSpec(field, knownContractNames)
	if err != nil {
		return fieldSpec{}, nil, fmt.Errorf(
			"python shared types: %s.%s: %w",
			contractName,
			field.Name,
			err,
		)
	}

	fieldImports := map[string]struct{}{}
	mergeImportSet(fieldImports, typeSpec.Imports)
	importTag := strings.TrimSpace(field.Tag.Get("py_import"))
	if importTag != "" {
		mergePythonImportTagLines(fieldImports, importTag, knownContractNames)
	}

	defaultExpr, err := pythonDefaultExpr(
		ownerType,
		field,
		typeSpec.TypeExpr,
		defaultSourcesByType,
	)
	if err != nil {
		return fieldSpec{}, nil, fmt.Errorf(
			"python shared types: %s.%s: %w",
			contractName,
			field.Name,
			err,
		)
	}
	typeExpr := typeSpec.TypeExpr
	if field.Type.Kind() == reflect.Pointer && !strings.Contains(typeExpr, " | None") {
		typeExpr += " | None"
	}
	if fieldAllowsMissing(field) && defaultExpr == "" {
		if !strings.Contains(typeExpr, " | None") {
			typeExpr += " | None"
		}
		defaultExpr = "None"
	}

	return fieldSpec{
		Name:        jsonName,
		TypeExpr:    typeExpr,
		DefaultExpr: defaultExpr,
	}, fieldImports, nil
}

func mergeImportSet(dst map[string]struct{}, src map[string]struct{}) {
	if dst == nil {
		return
	}
	for line := range src {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" {
			continue
		}
		dst[trimmed] = struct{}{}
	}
}

func mergePythonImportTagLines(
	dst map[string]struct{},
	importTag string,
	knownContractNames map[string]struct{},
) {
	for _, line := range strings.Split(importTag, "\n") {
		filtered := filteredPythonImportLine(line, knownContractNames)
		if filtered == "" {
			continue
		}
		dst[filtered] = struct{}{}
	}
}

func filteredPythonImportLine(
	line string,
	knownContractNames map[string]struct{},
) string {
	trimmed := strings.TrimSpace(line)
	if trimmed == "" {
		return ""
	}
	if !strings.HasPrefix(trimmed, "from ") {
		return trimmed
	}
	moduleAndNames := strings.TrimPrefix(trimmed, "from ")
	module, imported, ok := strings.Cut(moduleAndNames, " import ")
	if !ok {
		return trimmed
	}
	if strings.TrimSpace(module) == "setta.types.generated.go_shared_types" {
		return ""
	}

	kept := make([]string, 0)
	for _, part := range strings.Split(imported, ",") {
		part = strings.TrimSpace(part)
		if part == "" {
			continue
		}
		name := part
		if before, _, ok := strings.Cut(part, " as "); ok {
			name = strings.TrimSpace(before)
		}
		if _, local := knownContractNames[name]; local {
			continue
		}
		if replacement := localPythonContractReplacement(name, knownContractNames); replacement != "" {
			continue
		}
		kept = append(kept, part)
	}
	if len(kept) == 0 {
		return ""
	}
	return fmt.Sprintf("from %s import %s", strings.TrimSpace(module), strings.Join(kept, ", "))
}

func normalizedPythonTypeOverride(
	override string,
	knownContractNames map[string]struct{},
) string {
	override = strings.TrimSpace(override)
	if override == "" {
		return ""
	}
	for _, name := range referencedTypeNames(override) {
		replacement := localPythonContractReplacement(name, knownContractNames)
		if replacement == "" {
			continue
		}
		override = strings.ReplaceAll(override, name, replacement)
	}
	return override
}

func localPythonContractReplacement(
	name string,
	knownContractNames map[string]struct{},
) string {
	if !strings.HasSuffix(name, "WithDiscriminator") {
		return ""
	}
	baseName := strings.TrimSuffix(name, "WithDiscriminator")
	if _, ok := knownContractNames[baseName]; !ok {
		return ""
	}
	return baseName
}

func pythonTypeNameIsBuiltin(name string) bool {
	switch name {
	case "", "Any", "None", "bool", "bytes", "datetime", "dict", "float", "int", "list", "str":
		return true
	default:
		return false
	}
}

func referencedTypeNames(typeExpr string) []string {
	names := make([]string, 0)
	seen := map[string]struct{}{}
	var token strings.Builder
	flush := func() {
		if token.Len() == 0 {
			return
		}
		name := token.String()
		token.Reset()
		if name == "" {
			return
		}
		if _, ok := seen[name]; ok {
			return
		}
		seen[name] = struct{}{}
		names = append(names, name)
	}
	for _, char := range typeExpr {
		if char == '_' || unicode.IsLetter(char) || unicode.IsDigit(char) {
			token.WriteRune(char)
			continue
		}
		flush()
	}
	flush()
	return names
}

func visibleFields(modelType reflect.Type) []reflect.StructField {
	fields := make([]reflect.StructField, 0, modelType.NumField())
	for index := 0; index < modelType.NumField(); index++ {
		field := modelType.Field(index)
		if !field.IsExported() {
			continue
		}
		if field.Tag.Get("json") == "-" {
			continue
		}
		fields = append(fields, field)
	}
	return fields
}

func fieldJSONName(field reflect.StructField) (string, error) {
	tag := strings.TrimSpace(field.Tag.Get("json"))
	if tag == "" {
		return "", fmt.Errorf("missing json tag")
	}
	name := strings.TrimSpace(strings.Split(tag, ",")[0])
	if name == "" {
		return "", fmt.Errorf("missing json field name")
	}
	return name, nil
}

func fieldAllowsMissing(field reflect.StructField) bool {
	tag := strings.TrimSpace(field.Tag.Get("json"))
	if tag == "" {
		return false
	}
	parts := strings.Split(tag, ",")
	for _, part := range parts[1:] {
		if strings.TrimSpace(part) == "omitempty" {
			return true
		}
	}
	return false
}

type pythonTypeSpec struct {
	TypeExpr string
	Imports  map[string]struct{}
}

func pythonFieldTypeSpec(
	field reflect.StructField,
	knownContractNames map[string]struct{},
) (pythonTypeSpec, error) {
	if spec, ok, err := pythonTypeSpecFromSharedSchemaOverride(field, knownContractNames); ok || err != nil {
		return spec, err
	}
	return pythonTypeExprWithImports(
		field.Type,
		strings.TrimSpace(field.Tag.Get("py_type")),
		knownContractNames,
	)
}

func pythonTypeSpecFromSharedSchemaOverride(
	field reflect.StructField,
	knownContractNames map[string]struct{},
) (pythonTypeSpec, bool, error) {
	if strings.TrimSpace(field.Tag.Get("py_type")) != "" {
		return pythonTypeSpec{}, false, nil
	}

	override, ok, err := sharedtypes.SchemaFieldOverrideForField(field)
	if err != nil || !ok {
		return pythonTypeSpec{}, ok, err
	}

	switch {
	case override.Ref != "":
		typeName := strings.TrimSpace(override.Ref)
		if typeName == "" {
			return pythonTypeSpec{}, true, fmt.Errorf("shared schema ref contract name is required")
		}
		return pythonTypeSpec{TypeExpr: typeName}, true, nil
	case override.ItemsRef != "":
		switch field.Type.Kind() {
		case reflect.Slice, reflect.Array:
		default:
			return pythonTypeSpec{}, true, fmt.Errorf(
				"shared schema items ref requires slice or array field, got %s",
				field.Type,
			)
		}
		typeName := strings.TrimSpace(override.ItemsRef)
		if typeName == "" {
			return pythonTypeSpec{}, true, fmt.Errorf("shared schema items ref contract name is required")
		}
		return pythonTypeSpec{TypeExpr: "list[" + typeName + "]"}, true, nil
	case override.MapValueRef != "":
		return pythonTypeSpec{}, false, nil
	default:
		return pythonTypeSpec{}, false, nil
	}
}

func pythonTypeExpr(fieldType reflect.Type, override string) (string, error) {
	spec, err := pythonTypeExprWithImports(fieldType, override, nil)
	if err != nil {
		return "", err
	}
	return spec.TypeExpr, nil
}

func pythonTypeExprWithImports(
	fieldType reflect.Type,
	override string,
	knownContractNames map[string]struct{},
) (pythonTypeSpec, error) {
	override = normalizedPythonTypeOverride(override, knownContractNames)
	if spec, ok := overridePythonTypeSpec(override); ok {
		return spec, nil
	}
	if spec, ok, err := pythonSpecialTypeSpec(fieldType, knownContractNames); ok || err != nil {
		return spec, err
	}
	if spec, ok := pythonPrimitiveTypeSpec(fieldType); ok {
		return spec, nil
	}
	return pythonCompositeTypeSpec(fieldType, knownContractNames)
}

func overridePythonTypeSpec(override string) (pythonTypeSpec, bool) {
	override = strings.TrimSpace(override)
	if override == "" {
		return pythonTypeSpec{}, false
	}
	return pythonTypeSpec{TypeExpr: override}, true
}

func pythonSpecialTypeSpec(
	fieldType reflect.Type,
	knownContractNames map[string]struct{},
) (pythonTypeSpec, bool, error) {
	if fieldType == timeType {
		return pythonTypeSpec{TypeExpr: "datetime"}, true, nil
	}
	if fieldType == rawJSONType {
		return pythonTypeSpec{TypeExpr: "Any"}, true, nil
	}

	publicTypeName := pythonSharedContractNameForType(fieldType)
	if modulePath, ok := pythonExternalTypeModules[fieldType.PkgPath()]; ok &&
		fieldType.Name() != "" {
		if _, sameModule := knownContractNames[publicTypeName]; sameModule {
			return pythonTypeSpec{TypeExpr: publicTypeName}, true, nil
		}
		importLine := fmt.Sprintf("from %s import %s", modulePath, publicTypeName)
		return pythonTypeSpec{
			TypeExpr: publicTypeName,
			Imports: map[string]struct{}{
				importLine: {},
			},
		}, true, nil
	}

	if fieldType.Kind() == reflect.String && fieldType.Name() != "" {
		spec, ok, err := enumContractSpecIfConvertible(fieldType)
		if err != nil {
			return pythonTypeSpec{}, false, err
		}
		if ok {
			return pythonTypeSpec{TypeExpr: spec.Name}, true, nil
		}
	}
	return pythonTypeSpec{}, false, nil
}

func pythonPrimitiveTypeSpec(fieldType reflect.Type) (pythonTypeSpec, bool) {
	switch fieldType.Kind() {
	case reflect.String:
		return pythonTypeSpec{TypeExpr: "str"}, true
	case reflect.Bool:
		return pythonTypeSpec{TypeExpr: "bool"}, true
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return pythonTypeSpec{TypeExpr: "int"}, true
	case reflect.Float32, reflect.Float64:
		return pythonTypeSpec{TypeExpr: "float"}, true
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		if fieldType.Kind() == reflect.Uint8 {
			return pythonTypeSpec{TypeExpr: "bytes"}, true
		}
		return pythonTypeSpec{TypeExpr: "int"}, true
	case reflect.Interface:
		return pythonTypeSpec{TypeExpr: "Any"}, true
	default:
		return pythonTypeSpec{}, false
	}
}

func pythonCompositeTypeSpec(
	fieldType reflect.Type,
	knownContractNames map[string]struct{},
) (pythonTypeSpec, error) {
	switch fieldType.Kind() {
	case reflect.Pointer:
		elemSpec, err := pythonTypeExprWithImports(fieldType.Elem(), "", knownContractNames)
		if err != nil {
			return pythonTypeSpec{}, err
		}
		return pythonTypeSpec{
			TypeExpr: elemSpec.TypeExpr + " | None",
			Imports:  elemSpec.Imports,
		}, nil
	case reflect.Slice:
		if fieldType.Elem().Kind() == reflect.Uint8 {
			return pythonTypeSpec{TypeExpr: "bytes"}, nil
		}
		elemSpec, err := pythonTypeExprWithImports(fieldType.Elem(), "", knownContractNames)
		if err != nil {
			return pythonTypeSpec{}, err
		}
		return pythonTypeSpec{
			TypeExpr: "list[" + elemSpec.TypeExpr + "]",
			Imports:  elemSpec.Imports,
		}, nil
	case reflect.Array:
		elemSpec, err := pythonTypeExprWithImports(fieldType.Elem(), "", knownContractNames)
		if err != nil {
			return pythonTypeSpec{}, err
		}
		return pythonTypeSpec{
			TypeExpr: "list[" + elemSpec.TypeExpr + "]",
			Imports:  elemSpec.Imports,
		}, nil
	case reflect.Map:
		keySpec, err := pythonTypeExprWithImports(fieldType.Key(), "", knownContractNames)
		if err != nil {
			return pythonTypeSpec{}, err
		}
		valueSpec, err := pythonTypeExprWithImports(fieldType.Elem(), "", knownContractNames)
		if err != nil {
			return pythonTypeSpec{}, err
		}
		imports := map[string]struct{}{}
		mergeImportSet(imports, keySpec.Imports)
		mergeImportSet(imports, valueSpec.Imports)
		return pythonTypeSpec{
			TypeExpr: "dict[" + keySpec.TypeExpr + ", " + valueSpec.TypeExpr + "]",
			Imports:  imports,
		}, nil
	case reflect.Struct:
		return pythonTypeSpec{TypeExpr: pythonSharedContractNameForType(fieldType)}, nil
	default:
		return pythonTypeSpec{}, fmt.Errorf("unsupported type %s", fieldType)
	}
}

func pythonDefaultExpr(
	ownerType reflect.Type,
	field reflect.StructField,
	typeExpr string,
	defaultSourcesByType map[reflect.Type]reflect.Value,
) (string, error) {
	defaultTag := strings.TrimSpace(field.Tag.Get("py_default"))
	switch defaultTag {
	case "":
		if field.Type.Kind() == reflect.Pointer || strings.HasSuffix(typeExpr, " | None") {
			return "None", nil
		}
		return "", nil
	case "go_value":
		return pythonDefaultExprFromGoValue(ownerType, field, typeExpr, defaultSourcesByType)
	case "factory:list":
		return "Field(default_factory=list)", nil
	case "factory:dict":
		return "Field(default_factory=dict)", nil
	default:
		return defaultTag, nil
	}
}

func pythonDefaultExprFromGoValue(
	ownerType reflect.Type,
	field reflect.StructField,
	typeExpr string,
	defaultSourcesByType map[reflect.Type]reflect.Value,
) (string, error) {
	defaultValue, ok := pythonSharedDefaultValueForField(ownerType, field, defaultSourcesByType)
	if !ok {
		defaultValue = reflect.Zero(field.Type)
	}
	return pythonFieldDefaultExprFromValue(defaultValue, typeExpr)
}

func pythonFieldDefaultExprFromValue(value reflect.Value, typeExpr string) (string, error) {
	if !value.IsValid() {
		return "None", nil
	}
	if value.Kind() == reflect.Interface {
		if value.IsNil() {
			return "None", nil
		}
		return pythonFieldDefaultExprFromValue(value.Elem(), typeExpr)
	}
	if value.Kind() == reflect.Pointer {
		if value.IsNil() {
			return "None", nil
		}
		value = value.Elem()
	}
	if expr, ok := pythonEmptyCollectionDefaultExpr(value); ok {
		return expr, nil
	}
	if expr, ok := pythonScalarDefaultExpr(value); ok {
		return expr, nil
	}
	payload, err := json.Marshal(value.Interface())
	if err != nil {
		return "", err
	}
	return fmt.Sprintf(
		"Field(default_factory=lambda: TypeAdapter(%s).validate_json(%q))",
		typeExpr,
		string(payload),
	), nil
}

func pythonEmptyCollectionDefaultExpr(value reflect.Value) (string, bool) {
	switch value.Kind() {
	case reflect.Map:
		if value.IsNil() || value.Len() == 0 {
			return "Field(default_factory=dict)", true
		}
	case reflect.Slice:
		if value.Type().Elem().Kind() == reflect.Uint8 {
			return "", false
		}
		if value.IsNil() || value.Len() == 0 {
			return "Field(default_factory=list)", true
		}
	}
	return "", false
}

func pythonScalarDefaultExpr(value reflect.Value) (string, bool) {
	valueType := value.Type()
	if valueType.Kind() == reflect.String && valueType.Name() != "" && valueType.PkgPath() != "" {
		return "", false
	}
	switch value.Kind() {
	case reflect.String:
		return strconv.Quote(value.String()), true
	case reflect.Bool:
		if value.Bool() {
			return "True", true
		}
		return "False", true
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return strconv.FormatInt(value.Int(), 10), true
	case reflect.Uint, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr:
		return strconv.FormatUint(value.Uint(), 10), true
	case reflect.Uint8:
		return strconv.FormatUint(value.Uint(), 10), true
	case reflect.Float32:
		return pythonFloatLiteral(value.Float(), 32), true
	case reflect.Float64:
		return pythonFloatLiteral(value.Float(), 64), true
	default:
		return "", false
	}
}

func pythonFloatLiteral(value float64, bitSize int) string {
	literal := strconv.FormatFloat(value, 'f', -1, bitSize)
	if strings.ContainsRune(literal, '.') {
		return literal
	}
	return literal + ".0"
}

func renderFieldLine(field fieldSpec) string {
	line := "    " + field.Name + ": " + field.TypeExpr
	if field.DefaultExpr == "" {
		return line + "\n"
	}
	return line + " = " + field.DefaultExpr + "\n"
}

func sortedImportNames(imports map[string]struct{}) []string {
	names := make([]string, 0, len(imports))
	for name := range imports {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func pythonEnumMemberName(name string) string {
	if _, ok := pythonKeywords[name]; ok {
		return name + "_"
	}
	return name
}
