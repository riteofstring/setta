package agent

import (
	"errors"
	"fmt"
	"strings"

	"setta/internal/codexapp"
)

// TokenUsageBucket keeps evaluated-system cost separate from evaluator cost.
// A judge call is still made through the Agent boundary, but it must never be
// counted as work Setta spent completing the scenario.
type TokenUsageBucket string

const (
	TokenUsageBucketSystem TokenUsageBucket = "system"
	TokenUsageBucketJudge  TokenUsageBucket = "judge"
)

// TokenUsageRole is the accounting owner of one provider invocation. The four
// production values intentionally match the conversation role vocabulary while
// keeping the lower-level Agent package independent from conversation storage.
type TokenUsageRole string

const (
	TokenUsageRoleDirector  TokenUsageRole = "director"
	TokenUsageRoleAgent     TokenUsageRole = "agent"
	TokenUsageRoleNarrator  TokenUsageRole = "narrator"
	TokenUsageRoleSideAgent TokenUsageRole = "side_agent"
	TokenUsageRoleJudge     TokenUsageRole = "judge"
)

// TokenUsageAttribution binds an ephemeral provider turn to the resolved Setta
// invocation that owns it. InvocationID is generated by the durable owner
// before provider work begins; token evidence itself remains ephemeral.
type TokenUsageAttribution struct {
	Bucket          TokenUsageBucket `json:"bucket"`
	Role            TokenUsageRole   `json:"role"`
	InvocationID    string           `json:"invocationId"`
	Model           string           `json:"model"`
	ReasoningEffort string           `json:"reasoningEffort"`
	ServiceTier     *string          `json:"serviceTier"`
}

// TokenUsageObservation is the exact typed provider notification plus its
// Setta owner. Observers may persist it only to an explicitly ephemeral sink;
// it is never an Agent event or a durable conversation fact.
type TokenUsageObservation struct {
	Attribution      TokenUsageAttribution     `json:"attribution"`
	ProviderThreadID string                    `json:"providerThreadId"`
	ProviderTurnID   string                    `json:"providerTurnId"`
	TokenUsage       codexapp.ThreadTokenUsage `json:"tokenUsage"`
}

type TokenUsageObserver interface {
	ObserveTokenUsage(TokenUsageObservation) error
}

func (attribution TokenUsageAttribution) Validate() error {
	for _, field := range []struct {
		label string
		value string
	}{
		{label: "invocation id", value: attribution.InvocationID},
		{label: "model", value: attribution.Model},
		{label: "reasoning effort", value: attribution.ReasoningEffort},
	} {
		if err := validateRequiredTokenUsageString(field.label, field.value); err != nil {
			return err
		}
	}
	if err := validateOptionalTokenUsageString("service tier", attribution.ServiceTier); err != nil {
		return err
	}
	return validateTokenUsageRoleBucket(attribution.Bucket, attribution.Role)
}

func validateRequiredTokenUsageString(label string, value string) error {
	if strings.TrimSpace(value) == "" || strings.TrimSpace(value) != value {
		return fmt.Errorf("token usage %s is required without surrounding whitespace", label)
	}
	return nil
}

func validateOptionalTokenUsageString(label string, value *string) error {
	if value == nil {
		return nil
	}
	if err := validateRequiredTokenUsageString(label, *value); err != nil {
		return err
	}
	return nil
}

func validateTokenUsageRoleBucket(bucket TokenUsageBucket, role TokenUsageRole) error {
	switch bucket {
	case TokenUsageBucketSystem:
		switch role {
		case TokenUsageRoleDirector, TokenUsageRoleAgent, TokenUsageRoleNarrator, TokenUsageRoleSideAgent:
			return nil
		default:
			return fmt.Errorf("system token usage has unsupported role %q", role)
		}
	case TokenUsageBucketJudge:
		if role != TokenUsageRoleJudge {
			return fmt.Errorf("judge token usage has role %q, want judge", role)
		}
		return nil
	default:
		return fmt.Errorf("unsupported token usage bucket %q", bucket)
	}
}

func validateTokenUsageAttributionForInvocation(
	attribution TokenUsageAttribution,
	invocation Invocation,
) error {
	if err := attribution.Validate(); err != nil {
		return err
	}
	if attribution.Model != invocation.Model ||
		attribution.ReasoningEffort != invocation.ReasoningEffort ||
		!equalOptionalTokenUsageString(attribution.ServiceTier, invocation.ServiceTier) {
		return errors.New("token usage attribution does not match the provider invocation settings")
	}
	return nil
}

func equalOptionalTokenUsageString(left *string, right *string) bool {
	if left == nil || right == nil {
		return left == nil && right == nil
	}
	return *left == *right
}

func (observation TokenUsageObservation) Validate() error {
	if err := observation.Attribution.Validate(); err != nil {
		return err
	}
	if strings.TrimSpace(observation.ProviderThreadID) == "" ||
		strings.TrimSpace(observation.ProviderThreadID) != observation.ProviderThreadID ||
		strings.TrimSpace(observation.ProviderTurnID) == "" ||
		strings.TrimSpace(observation.ProviderTurnID) != observation.ProviderTurnID {
		return errors.New("token usage observation requires provider thread and turn ids without surrounding whitespace")
	}
	if observation.TokenUsage.ModelContextWindow != nil && *observation.TokenUsage.ModelContextWindow < 0 {
		return errors.New("token usage model context window must be non-negative")
	}
	for label, usage := range map[string]codexapp.TokenUsageBreakdown{
		"last":  observation.TokenUsage.Last,
		"total": observation.TokenUsage.Total,
	} {
		if err := validateTokenUsageBreakdown(label, usage); err != nil {
			return err
		}
	}
	return nil
}

func validateTokenUsageBreakdown(label string, usage codexapp.TokenUsageBreakdown) error {
	values := []int{
		usage.CachedInputTokens,
		usage.InputTokens,
		usage.OutputTokens,
		usage.ReasoningOutputTokens,
		usage.TotalTokens,
	}
	if usage.CacheWriteInputTokens != nil {
		values = append(values, *usage.CacheWriteInputTokens)
	}
	for _, value := range values {
		if value < 0 {
			return fmt.Errorf("token usage %s breakdown contains a negative value", label)
		}
	}
	return nil
}

func cloneTokenUsageAttribution(value TokenUsageAttribution) TokenUsageAttribution {
	cloned := value
	if value.ServiceTier != nil {
		serviceTier := *value.ServiceTier
		cloned.ServiceTier = &serviceTier
	}
	return cloned
}
