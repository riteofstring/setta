package main

import (
	"flag"
	"fmt"
	"os"
	"strings"

	"setta/internal/gotypediscovery"
)

type routeRegistryTarget struct {
	OutputPath string
	Package    string
	FuncName   string
	PkgPath    string
	Comment    string
}

func main() {
	write := flag.Bool("write", true, "write generated registry files")
	flag.Parse()

	targets := []routeRegistryTarget{
		{
			OutputPath: "internal/httpapi/discovered_routes_gen.go",
			Package:    "httpapi",
			FuncName:   "DiscoveredRouteConstants",
			PkgPath:    "setta/internal/httpapi",
			Comment:    "Code generated by ./scripts/go.sh run ./cmd/setta-gen-go-route-registries; DO NOT EDIT.",
		},
		{
			OutputPath: "internal/wsapi/discovered_routes_gen.go",
			Package:    "wsapi",
			FuncName:   "DiscoveredRouteConstants",
			PkgPath:    "setta/internal/wsapi",
			Comment:    "Code generated by ./scripts/go.sh run ./cmd/setta-gen-go-route-registries; DO NOT EDIT.",
		},
	}

	for _, target := range targets {
		routes, err := gotypediscovery.DiscoverPackageStringConstantsWithPrefix(target.PkgPath, "Route")
		if err != nil {
			fail("discover %s: %v", target.OutputPath, err)
		}
		contents := renderRouteRegistry(target, routes)
		if !*write {
			fmt.Printf("== %s ==\n%s\n", target.OutputPath, contents)
			continue
		}
		if err := os.WriteFile(target.OutputPath, []byte(contents), 0o644); err != nil {
			fail("write %s: %v", target.OutputPath, err)
		}
	}
}

func renderRouteRegistry(
	target routeRegistryTarget,
	routes []gotypediscovery.DiscoveredStringConstant,
) string {
	var builder strings.Builder
	builder.WriteString("// ")
	builder.WriteString(target.Comment)
	builder.WriteString("\n\n")
	builder.WriteString("package ")
	builder.WriteString(target.Package)
	builder.WriteString("\n\n")
	builder.WriteString("func ")
	builder.WriteString(target.FuncName)
	builder.WriteString("() []RouteConstant {\n")
	builder.WriteString("\treturn []RouteConstant{\n")
	for _, route := range routes {
		builder.WriteString("\t\t{Name: ")
		builder.WriteString(fmt.Sprintf("%q", route.Name))
		builder.WriteString(", Path: ")
		builder.WriteString(route.Name)
		builder.WriteString("},\n")
	}
	builder.WriteString("\t}\n")
	builder.WriteString("}\n")
	return builder.String()
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "setta-gen-go-route-registries: "+format+"\n", args...)
	os.Exit(1)
}
