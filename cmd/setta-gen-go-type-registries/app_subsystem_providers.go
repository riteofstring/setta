package main

import (
	"fmt"
	"os"
	"path"
	"strings"
)

func writeAppSubsystemProviderRegistry(
	entries []appSubsystemProviderEntry,
	write bool,
) error {
	contents := renderAppSubsystemProviderRegistry(entries)
	if !write {
		fmt.Printf("== %s ==\n%s\n", appSubsystemProviderOutputPath, contents)
		return nil
	}
	return os.WriteFile(appSubsystemProviderOutputPath, []byte(contents), 0o644)
}

func renderAppSubsystemProviderRegistry(entries []appSubsystemProviderEntry) string {
	var builder strings.Builder
	builder.WriteString("// Code generated by ./scripts/go.sh run ./cmd/setta-gen-go-type-registries; DO NOT EDIT.\n\n")
	builder.WriteString("package appsubsystemproviders\n\n")
	builder.WriteString("import plugins \"setta/internal/plugins\"\n\n")

	builder.WriteString("var discoveredProviderCapabilities = []plugins.PluginAppSubsystemFeatureManifest{\n")
	for _, entry := range entries {
		builder.WriteString("\t{\n")
		builder.WriteString(fmt.Sprintf("\t\tAppAuthoringUI: %t,\n", entry.Capabilities.AppAuthoringUI))
		builder.WriteString(fmt.Sprintf("\t\tAppPreviewUI: %t,\n", entry.Capabilities.AppPreviewUI))
		builder.WriteString(fmt.Sprintf("\t\tAppGenerationChatModes: %t,\n", entry.Capabilities.AppGenerationChatModes))
		builder.WriteString(fmt.Sprintf("\t\tAppDeploymentRuntime: %t,\n", entry.Capabilities.AppDeploymentRuntime))
		builder.WriteString("\t},\n")
	}
	builder.WriteString("}\n\n")
	builder.WriteString("func DiscoveredProviderCapabilities() []plugins.PluginAppSubsystemFeatureManifest {\n")
	builder.WriteString("\treturn append([]plugins.PluginAppSubsystemFeatureManifest(nil), discoveredProviderCapabilities...)\n")
	builder.WriteString("}\n")
	return builder.String()
}

func buildImportAliasesForPaths(targetPackage string, importPaths []string) map[string]string {
	aliases := map[string]string{}
	used := map[string]struct{}{
		targetPackage: {},
	}
	for _, importPath := range importPaths {
		base := strings.TrimSpace(path.Base(importPath))
		alias := sanitizeAlias(base)
		if alias == "" {
			alias = "pkg"
		}
		candidate := alias
		suffix := 2
		for {
			if _, exists := used[candidate]; !exists {
				break
			}
			candidate = fmt.Sprintf("%s%d", alias, suffix)
			suffix++
		}
		used[candidate] = struct{}{}
		aliases[importPath] = candidate
	}
	return aliases
}

func renderDefaultProviderCall(
	entry defaultProviderEntry,
	importAliases map[string]string,
) string {
	qualifiedName := entry.ProviderFuncName
	if alias := importAliases[entry.ProviderPackagePath]; alias != "" {
		qualifiedName = alias + "." + qualifiedName
	}
	return qualifiedName + "()"
}
