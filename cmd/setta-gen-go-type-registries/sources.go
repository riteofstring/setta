func writeRegistryTargets(
	targets []registryTarget,
	write bool,
) ([]registryEntry, error) {
	var frontendDefaultProviderEntries []registryEntry
	for _, target := range targets {
		entries, err := discoverRegistryEntries(target)
		if err != nil {
			return nil, fmt.Errorf("discover %s: %w", target.OutputPath, err)
		}
		if target.OutputPath == "internal/frontendbindings/discovered_type_roots_gen.go" ||
			target.OutputPath == "internal/frontendbindings/discovered_endpoint_contract_types_gen.go" {
			frontendDefaultProviderEntries = append(frontendDefaultProviderEntries, entries...)
		}
		if err := writeRegistryTarget(target, entries, write); err != nil {
			return nil, err
		}
	}
	return frontendDefaultProviderEntries, nil
}

func writeRegistryTarget(
	target registryTarget,
	entries []registryEntry,
	write bool,
) error {
	contents := renderRegistry(target, entries)
	if !write {
		fmt.Printf("== %s ==\n%s\n", target.OutputPath, contents)
		return nil
	}
	if err := os.WriteFile(target.OutputPath, []byte(contents), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", target.OutputPath, err)
	}
	return nil
}

func pluginAppDefinitionPackagePaths() ([]string, error) {
	repoRoot, err := generatorRepoRoot()
	if err != nil {
		return nil, err
	}
	return pluginAppDefinitionPackagePathsFromRepoRoot(repoRoot)
}

func pluginAppDefinitionPackagePathsFromRepoRoot(
	repoRoot string,
) ([]string, error) {
	packages, err := walkPackagePaths(repoRoot, filepath.Join(repoRoot, "plugins"))
	if err != nil {
		return nil, err
	}
	filtered := make([]string, 0, len(packages))
	for _, pkgPath := range packages {
		if !strings.HasSuffix(pkgPath, "/backend/appdefinition") {
			continue
		}
		filtered = append(filtered, pkgPath)
	}
	return filtered, nil
}

func appSubsystemProviders() ([]appSubsystemProviderEntry, error) {
	repoRoot, err := generatorRepoRoot()
	if err != nil {
		return nil, err
	}
	return appSubsystemProvidersFromRepoRoot(repoRoot)
}

func appSubsystemProvidersFromRepoRoot(
	repoRoot string,
) ([]appSubsystemProviderEntry, error) {
	pluginRoots, err := pluginRootPathsFromRepoRoot(repoRoot)
	if err != nil {
		return nil, err
	}

	entries := make([]appSubsystemProviderEntry, 0, len(pluginRoots))
	for _, pluginRoot := range pluginRoots {
		pluginID := filepath.Base(pluginRoot)
		manifest, err := plugins.LoadPluginManifest(pluginRoot, pluginID)
		if err != nil {
			return nil, err
		}
		if manifest.Backend == nil ||
			manifest.FeatureCapabilities == nil ||
			manifest.FeatureCapabilities.AppSubsystem == nil {
			continue
		}

		entries = append(entries, appSubsystemProviderEntry{
			PluginID:     manifest.ID,
			Capabilities: *manifest.FeatureCapabilities.AppSubsystem,
		})
	}

	sort.Slice(entries, func(i int, j int) bool {
		return entries[i].PluginID < entries[j].PluginID
	})
	return entries, nil
}

func pluginRootPathsFromRepoRoot(repoRoot string) ([]string, error) {
	pluginsRoot := filepath.Join(repoRoot, "plugins")
	pluginRoots := []string{}
	if _, err := os.Stat(pluginsRoot); errors.Is(err, os.ErrNotExist) {
		return pluginRoots, nil
	} else if err != nil {
		return nil, err
	}

	if err := filepath.WalkDir(pluginsRoot, func(current string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !entry.IsDir() {
			return nil
		}
		if shouldSkipInternalPackageDir(entry.Name()) {
			return filepath.SkipDir
		}
		manifestPath := filepath.Join(current, "setta.plugin.json")
		info, statErr := os.Stat(manifestPath)
		switch {
		case errors.Is(statErr, os.ErrNotExist):
			return nil
		case statErr != nil:
			return statErr
		case info.IsDir():
			return nil
		default:
			pluginRoots = append(pluginRoots, current)
			return filepath.SkipDir
		}
	}); err != nil {
		return nil, err
	}

	sort.Strings(pluginRoots)
	return pluginRoots, nil
}
