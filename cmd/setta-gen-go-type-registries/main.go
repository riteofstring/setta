package main

import (
	"flag"
	"fmt"
	"os"
	"strings"

	"setta/internal/gotypediscovery"
)

type registryTarget struct {
	OutputPath string
	Package    string
	FuncName   string
	PkgPath    string
	Comment    string
}

func main() {
	write := flag.Bool("write", true, "write generated registry files")
	flag.Parse()

	targets := []registryTarget{
		{
			OutputPath: "internal/frontendbindings/discovered_type_roots_gen.go",
			Package:    "frontendbindings",
			FuncName:   "DiscoveredConvertibleTypes",
			PkgPath:    "setta/internal/frontendbindings",
			Comment:    "Code generated by ./scripts/go.sh run ./cmd/setta-gen-go-type-registries; DO NOT EDIT.",
		},
		{
			OutputPath: "internal/pythonsdkcontracts/discovered_contract_types_gen.go",
			Package:    "pythonsdkcontracts",
			FuncName:   "discoveredContractTypes",
			PkgPath:    "setta/internal/pythonsdkcontracts",
			Comment:    "Code generated by ./scripts/go.sh run ./cmd/setta-gen-go-type-registries; DO NOT EDIT.",
		},
	}

	for _, target := range targets {
		discovered, err := gotypediscovery.DiscoverPackageTypes(target.PkgPath)
		if err != nil {
			fail("discover %s: %v", target.PkgPath, err)
		}
		contents := renderRegistry(target, discovered)
		if !*write {
			fmt.Printf("== %s ==\n%s\n", target.OutputPath, contents)
			continue
		}
		if err := os.WriteFile(target.OutputPath, []byte(contents), 0o644); err != nil {
			fail("write %s: %v", target.OutputPath, err)
		}
	}
}

func renderRegistry(target registryTarget, discovered []gotypediscovery.DiscoveredType) string {
	var builder strings.Builder
	builder.WriteString("// ")
	builder.WriteString(target.Comment)
	builder.WriteString("\n\n")
	builder.WriteString("package ")
	builder.WriteString(target.Package)
	builder.WriteString("\n\n")
	builder.WriteString("import \"reflect\"\n\n")
	builder.WriteString("func ")
	builder.WriteString(target.FuncName)
	builder.WriteString("() []reflect.Type {\n")
	builder.WriteString("\treturn []reflect.Type{\n")
	for _, discoveredType := range discovered {
		builder.WriteString("\t\t")
		builder.WriteString(renderReflectExpr(discoveredType))
		builder.WriteString(",\n")
	}
	builder.WriteString("\t}\n")
	builder.WriteString("}\n")
	return builder.String()
}

func renderReflectExpr(discoveredType gotypediscovery.DiscoveredType) string {
	switch discoveredType.Kind {
	case gotypediscovery.TypeKindArray:
		return fmt.Sprintf("reflect.TypeOf(%s{})", discoveredType.Name)
	case gotypediscovery.TypeKindBool:
		return fmt.Sprintf("reflect.TypeOf(%s(false))", discoveredType.Name)
	case gotypediscovery.TypeKindFloat:
		return fmt.Sprintf("reflect.TypeOf(%s(0))", discoveredType.Name)
	case gotypediscovery.TypeKindStruct:
		return fmt.Sprintf("reflect.TypeOf(%s{})", discoveredType.Name)
	case gotypediscovery.TypeKindInterface:
		return fmt.Sprintf("reflect.TypeOf((*%s)(nil)).Elem()", discoveredType.Name)
	case gotypediscovery.TypeKindInt:
		return fmt.Sprintf("reflect.TypeOf(%s(0))", discoveredType.Name)
	case gotypediscovery.TypeKindMap:
		return fmt.Sprintf("reflect.TypeOf(%s(nil))", discoveredType.Name)
	case gotypediscovery.TypeKindSlice:
		return fmt.Sprintf("reflect.TypeOf(%s(nil))", discoveredType.Name)
	case gotypediscovery.TypeKindString:
		return fmt.Sprintf("reflect.TypeOf(%s(\"\"))", discoveredType.Name)
	case gotypediscovery.TypeKindUint:
		return fmt.Sprintf("reflect.TypeOf(%s(0))", discoveredType.Name)
	default:
		fail("unsupported discovered type kind %q for %s", discoveredType.Kind, discoveredType.Name)
		return ""
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "setta-gen-go-type-registries: "+format+"\n", args...)
	os.Exit(1)
}
