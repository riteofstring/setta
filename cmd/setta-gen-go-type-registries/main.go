func appSubsystemProvidersFromRepoRoot(
	repoRoot string,
) ([]appSubsystemProviderEntry, error) {
	pluginRoots, err := pluginRootPathsFromRepoRoot(repoRoot)
	if err != nil {
		return nil, err
	}

	entries := make([]appSubsystemProviderEntry, 0, len(pluginRoots))
	for _, pluginRoot := range pluginRoots {
		pluginID := filepath.Base(pluginRoot)
		manifest, err := plugins.LoadPluginManifest(pluginRoot, pluginID)
		if err != nil {
			return nil, err
		}
		if manifest.Backend == nil ||
			manifest.FeatureCapabilities == nil ||
			manifest.FeatureCapabilities.AppSubsystem == nil {
			continue
		}

		backendRoot := filepath.Join(pluginRoot, "backend")
		hasGoFiles, err := directoryHasNonTestGoFiles(backendRoot)
		if err != nil {
			return nil, err
		}
		if !hasGoFiles {
			continue
		}

		backendPackagePath, err := internalPackagePath(repoRoot, backendRoot)
		if err != nil {
			return nil, err
		}
		entries = append(entries, appSubsystemProviderEntry{
			PluginID:           manifest.ID,
			BackendPackagePath: backendPackagePath,
			Capabilities:       *manifest.FeatureCapabilities.AppSubsystem,
		})
	}

	sort.Slice(entries, func(i int, j int) bool {
		return entries[i].PluginID < entries[j].PluginID
	})
	return entries, nil
}

func pluginRootPathsFromRepoRoot(repoRoot string) ([]string, error) {
	pluginsRoot := filepath.Join(repoRoot, "plugins")
	pluginRoots := []string{}
	if _, err := os.Stat(pluginsRoot); errors.Is(err, os.ErrNotExist) {
		return pluginRoots, nil
	} else if err != nil {
		return nil, err
	}

	if err := filepath.WalkDir(pluginsRoot, func(current string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !entry.IsDir() {
			return nil
		}
		if shouldSkipInternalPackageDir(entry.Name()) {
			return filepath.SkipDir
		}
		manifestPath := filepath.Join(current, "setta.plugin.json")
		info, statErr := os.Stat(manifestPath)
		switch {
		case errors.Is(statErr, os.ErrNotExist):
			return nil
		case statErr != nil:
			return statErr
		case info.IsDir():
			return nil
		default:
			pluginRoots = append(pluginRoots, current)
			return filepath.SkipDir
		}
	}); err != nil {
		return nil, err
	}

	sort.Strings(pluginRoots)
	return pluginRoots, nil
}

func discoverRegistryEntries(target registryTarget) ([]registryEntry, error) {
	seenEntries := map[string]struct{}{}
	entries := []registryEntry{}
	for _, source := range target.Sources {
		discovered, err := gotypediscovery.DiscoverPackageTypesWithOptions(
			source.PkgPath,
			gotypediscovery.DiscoverOptions{
				RequireJSONTaggedStructs: source.RequireJSONTaggedStructs,
				IncludeZeroFieldStructs:  source.IncludeZeroFieldStructs,
				IncludeInterfaces:        source.IncludeInterfaces,
				IncludeCollectionAliases: source.IncludeCollectionAliases,
				IncludeNonStringScalars:  source.IncludeNonStringScalars,
			},
		)
		if err != nil {
			return nil, fmt.Errorf("discover %s: %w", source.PkgPath, err)
		}
		for _, discoveredType := range discovered {
			key := source.PkgPath + "\x00" + discoveredType.Name
			if _, alreadySeen := seenEntries[key]; alreadySeen {
				continue
			}
			seenEntries[key] = struct{}{}
			entries = append(entries, registryEntry{
				Type:    discoveredType,
				PkgPath: source.PkgPath,
			})
		}
	}
	for _, extraEntry := range explicitRegistryEntries(target) {
		key := extraEntry.PkgPath + "\x00" + extraEntry.Type.Name
		if _, alreadySeen := seenEntries[key]; alreadySeen {
			continue
		}
		seenEntries[key] = struct{}{}
		entries = append(entries, extraEntry)
	}
	return entries, nil
}

