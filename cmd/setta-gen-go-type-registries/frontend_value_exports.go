package main

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"setta/internal/gotypediscovery"
)

func writeFrontendValueExportRegistry(write bool) error {
	entries, err := discoverFrontendValueExportEntries()
	if err != nil {
		return err
	}
	contents := renderFrontendValueExportRegistry(entries)
	if !write {
		fmt.Printf("== %s ==\n%s\n", frontendValueExportOutputPath, contents)
		return nil
	}
	return os.WriteFile(frontendValueExportOutputPath, []byte(contents), 0o644)
}

func discoverFrontendValueExportEntries() ([]frontendValueExportEntry, error) {
	packages, err := frontendValueExportPackagePaths()
	if err != nil {
		return nil, err
	}
	return discoverFrontendValueExportEntriesFromPackages(packages)
}

func discoverFrontendValueExportEntriesFromPackages(
	packages []string,
) ([]frontendValueExportEntry, error) {
	entriesByName := map[string]frontendValueExportEntry{}
	for _, pkgPath := range packages {
		functions, err := gotypediscovery.DiscoverPackageZeroArgFunctionsWithPrefix(
			pkgPath,
			"FrontendValue",
		)
		if err != nil {
			return nil, fmt.Errorf("discover frontend value exports in %s: %w", pkgPath, err)
		}
		for _, function := range functions {
			name, err := frontendValueExportName(pkgPath, function.Name)
			if err != nil {
				return nil, err
			}
			entry := frontendValueExportEntry{
				Name:                name,
				ProviderPackagePath: pkgPath,
				ProviderFuncName:    function.Name,
			}
			if existing, ok := entriesByName[name]; ok &&
				(existing.ProviderPackagePath != entry.ProviderPackagePath ||
					existing.ProviderFuncName != entry.ProviderFuncName) {
				return nil, fmt.Errorf(
					"multiple frontend value exports discovered for %s: %s.%s and %s.%s",
					name,
					existing.ProviderPackagePath,
					existing.ProviderFuncName,
					entry.ProviderPackagePath,
					entry.ProviderFuncName,
				)
			}
			entriesByName[name] = entry
		}
	}

	entries := make([]frontendValueExportEntry, 0, len(entriesByName))
	for _, entry := range entriesByName {
		entries = append(entries, entry)
	}
	sort.Slice(entries, func(i, j int) bool {
		return entries[i].Name < entries[j].Name
	})
	return entries, nil
}

func frontendValueExportName(pkgPath string, functionName string) (string, error) {
	name := strings.TrimPrefix(functionName, "FrontendValue")
	if strings.TrimSpace(name) == "" {
		return "", fmt.Errorf("%s.%s has an empty export name", pkgPath, functionName)
	}
	pluginID, ok := pluginIDFromPackagePath(pkgPath)
	if !ok {
		return name, nil
	}
	return pluginID + "/" + name, nil
}

func pluginIDFromPackagePath(pkgPath string) (string, bool) {
	trimmed := strings.TrimSpace(pkgPath)
	if !strings.HasPrefix(trimmed, "setta/plugins/") {
		return "", false
	}
	segments := strings.Split(trimmed, "/")
	if len(segments) < 3 {
		return "", false
	}
	pluginID := strings.TrimSpace(segments[2])
	if pluginID == "" {
		return "", false
	}
	return pluginID, true
}

func renderFrontendValueExportRegistry(entries []frontendValueExportEntry) string {
	var builder strings.Builder
	builder.WriteString("// Code generated by ./scripts/go.sh run ./cmd/setta-gen-go-type-registries; DO NOT EDIT.\n\n")
	builder.WriteString("package " + frontendValueExportPackage + "\n\n")

	importPaths := frontendValueExportImportPaths(entries)
	if len(importPaths) == 0 {
		builder.WriteString("import \"reflect\"\n\n")
	} else {
		builder.WriteString("import (\n")
		builder.WriteString("\t\"reflect\"\n")
		importAliases := buildImportAliasesForPaths(frontendValueExportPackage, importPaths)
		for _, importPath := range importPaths {
			builder.WriteString("\t")
			builder.WriteString(importAliases[importPath])
			builder.WriteString(" ")
			builder.WriteString(fmt.Sprintf("%q", importPath))
			builder.WriteString("\n")
		}
		builder.WriteString(")\n\n")
	}

	builder.WriteString("func DiscoveredValueExports() []ValueExport {\n")
	builder.WriteString("\treturn []ValueExport{\n")
	importAliases := buildImportAliasesForPaths(frontendValueExportPackage, importPaths)
	for _, entry := range entries {
		builder.WriteString("\t\t{\n")
		builder.WriteString("\t\t\tName: ")
		builder.WriteString(fmt.Sprintf("%q", entry.Name))
		builder.WriteString(",\n")
		builder.WriteString("\t\t\tType: reflect.TypeOf(")
		builder.WriteString(renderFrontendValueExportCall(entry, importAliases))
		builder.WriteString("),\n")
		builder.WriteString("\t\t\tValue: func() any {\n")
		builder.WriteString("\t\t\t\treturn ")
		builder.WriteString(renderFrontendValueExportCall(entry, importAliases))
		builder.WriteString("\n")
		builder.WriteString("\t\t\t},\n")
		builder.WriteString("\t\t},\n")
	}
	builder.WriteString("\t}\n")
	builder.WriteString("}\n")
	return builder.String()
}

func frontendValueExportImportPaths(entries []frontendValueExportEntry) []string {
	imports := []string{}
	seen := map[string]struct{}{}
	for _, entry := range entries {
		if entry.ProviderPackagePath == "setta/internal/"+frontendValueExportPackage || strings.TrimSpace(entry.ProviderPackagePath) == "" {
			continue
		}
		if _, ok := seen[entry.ProviderPackagePath]; ok {
			continue
		}
		seen[entry.ProviderPackagePath] = struct{}{}
		imports = append(imports, entry.ProviderPackagePath)
	}
	sort.Strings(imports)
	return imports
}

func renderFrontendValueExportCall(
	entry frontendValueExportEntry,
	importAliases map[string]string,
) string {
	qualifiedName := entry.ProviderFuncName
	if alias := importAliases[entry.ProviderPackagePath]; alias != "" {
		qualifiedName = alias + "." + qualifiedName
	}
	return qualifiedName + "()"
}
