package main

import (
	"fmt"
	"os"
	"reflect"
	"sort"
	"strings"

	"setta/internal/gotypediscovery"
)

const frontendContractNamesOutputPath = "internal/frontendbindings/discovered_contract_names_gen.go"

func writeFrontendContractNameRegistry(write bool) error {
	entries := gotypediscovery.DiscoverFrontendContractNameEntries()
	contents := renderFrontendContractNameRegistry(entries)
	if !write {
		fmt.Printf("== %s ==\n%s\n", frontendContractNamesOutputPath, contents)
		return nil
	}
	return os.WriteFile(frontendContractNamesOutputPath, []byte(contents), 0o644)
}

func renderFrontendContractNameRegistry(entries []gotypediscovery.FrontendContractNameEntry) string {
	var builder strings.Builder
	builder.WriteString("// Code generated by ./scripts/go.sh run ./cmd/setta-gen-go-type-registries; DO NOT EDIT.\n\n")
	builder.WriteString("package frontendbindings\n\n")

	importPaths := frontendContractNameImportPaths(entries)
	if len(importPaths) == 0 {
		builder.WriteString("import \"reflect\"\n\n")
	} else {
		builder.WriteString("import (\n")
		builder.WriteString("\t\"reflect\"\n")
		importAliases := buildImportAliasesForPaths("frontendbindings", importPaths)
		for _, importPath := range importPaths {
			builder.WriteString("\t")
			builder.WriteString(importAliases[importPath])
			builder.WriteString(" ")
			builder.WriteString(fmt.Sprintf("%q", importPath))
			builder.WriteString("\n")
		}
		builder.WriteString(")\n\n")
	}

	builder.WriteString("var frontendBindingGeneratedTypeNamesByType = map[reflect.Type]string{\n")
	importAliases := buildImportAliasesForPaths("frontendbindings", importPaths)
	for _, entry := range entries {
		builder.WriteString("\t")
		builder.WriteString(renderFrontendContractReflectExpr(entry.Type, importAliases))
		builder.WriteString(": ")
		builder.WriteString(fmt.Sprintf("%q", entry.Name))
		builder.WriteString(",\n")
	}
	builder.WriteString("}\n")
	return builder.String()
}

func frontendContractNameImportPaths(entries []gotypediscovery.FrontendContractNameEntry) []string {
	imports := []string{}
	seen := map[string]struct{}{}
	for _, entry := range entries {
		importPath := strings.TrimSpace(entry.Type.PkgPath())
		if importPath == "" || importPath == "setta/internal/frontendbindings" {
			continue
		}
		if _, ok := seen[importPath]; ok {
			continue
		}
		seen[importPath] = struct{}{}
		imports = append(imports, importPath)
	}
	sort.Strings(imports)
	return imports
}

func renderFrontendContractReflectExpr(
	t reflect.Type,
	importAliases map[string]string,
) string {
	qualifiedName := t.Name()
	if alias := importAliases[t.PkgPath()]; alias != "" {
		qualifiedName = alias + "." + qualifiedName
	}

	switch t.Kind() {
	case reflect.Array:
		return fmt.Sprintf("reflect.TypeOf(%s{})", qualifiedName)
	case reflect.Bool:
		return fmt.Sprintf("reflect.TypeOf(%s(false))", qualifiedName)
	case reflect.Float32, reflect.Float64:
		return fmt.Sprintf("reflect.TypeOf(%s(0))", qualifiedName)
	case reflect.Struct:
		return fmt.Sprintf("reflect.TypeOf(%s{})", qualifiedName)
	case reflect.Interface:
		return fmt.Sprintf("reflect.TypeOf((*%s)(nil)).Elem()", qualifiedName)
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return fmt.Sprintf("reflect.TypeOf(%s(0))", qualifiedName)
	case reflect.Map:
		return fmt.Sprintf("reflect.TypeOf(%s(nil))", qualifiedName)
	case reflect.Slice:
		return fmt.Sprintf("reflect.TypeOf(%s(nil))", qualifiedName)
	case reflect.String:
		return fmt.Sprintf("reflect.TypeOf(%s(\"\"))", qualifiedName)
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr:
		return fmt.Sprintf("reflect.TypeOf(%s(0))", qualifiedName)
	default:
		fail("unsupported reflect kind %q for generated frontend contract name %s", t.Kind(), t)
		return ""
	}
}
