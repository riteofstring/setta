// Command generate-artifact-catalog renders the TypeScript half of the
// setta.artifacts.v1 artifact catalog from its Go owner.
//
// It emits two things:
//
//   - the catalog identity, the component-name union, and the OpenUI library
//     JSON Schema the pinned upstream parser compiles into its
//     positional-argument map
//   - the accepted conformance corpus, each fixture carried with the component
//     tree Setta's own compiler produced for it
//
// Together they let the desktop conformance suite prove the Phase 0 gate of the
// OpenUI artifact system plan: that every document Setta's backend accepts is
// interpreted the same way by the pinned upstream OpenUI parser.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"setta/internal/conversation/artifactdoc"
)

const generatedHeader = "// Code generated by ./scripts/go.sh run ./cmd/generate-artifact-catalog; DO NOT EDIT.\n\n"

func main() {
	outputDir := flag.String(
		"output-dir",
		"desktop/src/renderer/src/features/artifacts/generated",
		"generated TypeScript artifact catalog directory",
	)
	flag.Parse()

	catalog := artifactdoc.SettaCatalogV1()
	if err := writeCatalog(*outputDir, catalog); err != nil {
		fatalf("write artifact catalog: %v", err)
	}
	if err := writeCorpus(filepath.Join(*outputDir, "conformance-corpus"), catalog); err != nil {
		fatalf("write artifact conformance corpus: %v", err)
	}
}

// member is one key/value pair of an ordered JSON object.
//
// The upstream parser maps a component's positional arguments through the key
// order of its schema properties, so the generated schema has to carry the
// catalog's declared order rather than Go's map iteration order.
type member struct {
	key   string
	value any
}

type object []member

func (fields object) MarshalJSON() ([]byte, error) {
	var output bytes.Buffer
	output.WriteByte('{')
	for index, field := range fields {
		if index > 0 {
			output.WriteByte(',')
		}
		key, err := json.Marshal(field.key)
		if err != nil {
			return nil, fmt.Errorf("marshal key %q: %w", field.key, err)
		}
		output.Write(key)
		output.WriteByte(':')
		value, err := json.Marshal(field.value)
		if err != nil {
			return nil, fmt.Errorf("marshal value for %q: %w", field.key, err)
		}
		output.Write(value)
	}
	output.WriteByte('}')
	return output.Bytes(), nil
}

func writeCatalog(outputDir string, catalog artifactdoc.Catalog) error {
	if err := os.MkdirAll(outputDir, 0o755); err != nil {
		return fmt.Errorf("create generated directory: %w", err)
	}
	source, err := renderCatalog(catalog)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(outputDir, "artifact-catalog.ts"), source, 0o644); err != nil {
		return fmt.Errorf("write catalog module: %w", err)
	}
	return nil
}

func renderCatalog(catalog artifactdoc.Catalog) ([]byte, error) {
	schema, err := json.MarshalIndent(object{{key: "$defs", value: catalogDefinitions(catalog)}}, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("marshal catalog schema: %w", err)
	}
	var output bytes.Buffer
	output.WriteString(generatedHeader)
	output.WriteString("/** The one composition format Setta accepts for artifact documents. */\n")
	fmt.Fprintf(&output, "export const artifactDocumentLanguage = %q;\n\n", string(catalog.Language))
	output.WriteString("/** The frozen catalog the renderer selects its component map by. */\n")
	fmt.Fprintf(&output, "export const artifactCatalogId = %q;\n\n", string(catalog.ID))
	output.WriteString("/** The one component a document's root statement may call. */\n")
	fmt.Fprintf(&output, "export const artifactCatalogRootComponent = %q;\n\n", string(catalog.Root))
	output.WriteString("/** Every model-visible component, in catalog order. */\n")
	output.WriteString("export const artifactComponentNames = [\n")
	for _, name := range catalog.Names() {
		fmt.Fprintf(&output, "  %q,\n", string(name))
	}
	output.WriteString("] as const;\n\n")
	output.WriteString("export type ArtifactComponentName = (typeof artifactComponentNames)[number];\n\n")
	output.WriteString("/** One compiled component. Nested components appear inside `props`. */\n")
	output.WriteString("export interface ArtifactDocumentNode {\n")
	output.WriteString("  readonly component: ArtifactComponentName;\n")
	output.WriteString("  readonly props: Readonly<Record<string, unknown>>;\n")
	output.WriteString("}\n\n")
	output.WriteString("/** One component's entry in the library JSON Schema. */\n")
	output.WriteString("export interface ArtifactComponentSchema {\n")
	output.WriteString("  readonly description: string;\n")
	output.WriteString("  readonly properties: Record<string, unknown>;\n")
	output.WriteString("  readonly required: string[];\n")
	output.WriteString("}\n\n")
	output.WriteString("/**\n")
	output.WriteString(" * The library JSON Schema the pinned upstream OpenUI parser compiles into its\n")
	output.WriteString(" * positional-argument map: property order is argument order, and `required`\n")
	output.WriteString(" * decides which trailing arguments may be omitted.\n")
	output.WriteString(" *\n")
	output.WriteString(" * No property carries a JSON Schema `default`. Setta's compiler leaves a\n")
	output.WriteString(" * skipped optional argument absent instead of substituting a value, and the\n")
	output.WriteString(" * upstream parser substitutes a declared default, so a default here would put\n")
	output.WriteString(" * the two sides out of agreement.\n")
	output.WriteString(" */\n")
	output.WriteString("export const artifactCatalogSchema: {\n")
	output.WriteString("  readonly $defs: Record<ArtifactComponentName, ArtifactComponentSchema>;\n")
	output.WriteString("} = ")
	output.Write(schema)
	output.WriteString(";\n")
	return output.Bytes(), nil
}

func catalogDefinitions(catalog artifactdoc.Catalog) object {
	definitions := make(object, 0, len(catalog.Components))
	for _, component := range catalog.Components {
		definitions = append(definitions, member{key: string(component.Name), value: componentDefinition(component)})
	}
	return definitions
}

func componentDefinition(component artifactdoc.Component) object {
	properties := make(object, 0, len(component.Properties))
	required := make([]string, 0, len(component.Properties))
	for _, property := range component.Properties {
		properties = append(properties, member{
			key:   property.Name,
			value: valueDefinition(property.Schema, property.Description),
		})
		if property.Required {
			required = append(required, property.Name)
		}
	}
	return object{
		{key: "description", value: component.Summary},
		{key: "properties", value: properties},
		{key: "required", value: required},
	}
}

// valueDefinition renders one property, element, or field schema as JSON
// Schema. Every constraint the catalog can state exactly is carried through;
// the byte limits and string safety rules are deliberately not, because they
// are backend acceptance rules rather than parser behavior.
func valueDefinition(schema artifactdoc.ValueSchema, description string) object {
	definition := object{}
	if description != "" {
		definition = append(definition, member{key: "description", value: description})
	}
	switch schema.Kind {
	case artifactdoc.ValueKindString:
		definition = append(definition, member{key: "type", value: "string"})
	case artifactdoc.ValueKindEnum:
		definition = append(definition,
			member{key: "type", value: "string"},
			member{key: "enum", value: schema.EnumValues},
		)
	case artifactdoc.ValueKindNumber:
		definition = append(definition, member{key: "type", value: "number"})
		if schema.Integer {
			definition = append(definition, member{key: "multipleOf", value: 1})
		}
		if schema.Minimum != nil {
			definition = append(definition, member{key: "minimum", value: *schema.Minimum})
		}
		if schema.Maximum != nil {
			definition = append(definition, member{key: "maximum", value: *schema.Maximum})
		}
	case artifactdoc.ValueKindBoolean:
		definition = append(definition, member{key: "type", value: "boolean"})
	case artifactdoc.ValueKindComponent:
		definition = append(definition,
			member{key: "type", value: "object"},
			member{key: "oneOf", value: componentReferences(schema.Components)},
		)
	case artifactdoc.ValueKindList:
		definition = append(definition,
			member{key: "type", value: "array"},
			member{key: "items", value: valueDefinition(*schema.Element, "")},
		)
		if schema.MinItems > 0 {
			definition = append(definition, member{key: "minItems", value: schema.MinItems})
		}
		if schema.MaxItems > 0 {
			definition = append(definition, member{key: "maxItems", value: schema.MaxItems})
		}
	case artifactdoc.ValueKindObject:
		fields := make(object, 0, len(schema.Fields))
		required := make([]string, 0, len(schema.Fields))
		for _, field := range schema.Fields {
			fields = append(fields, member{key: field.Name, value: valueDefinition(field.Schema, field.Description)})
			if field.Required {
				required = append(required, field.Name)
			}
		}
		definition = append(definition,
			member{key: "type", value: "object"},
			member{key: "properties", value: fields},
			member{key: "required", value: required},
			member{key: "additionalProperties", value: false},
		)
	default:
		// The catalog is a Go-owned constant, so an unhandled kind is a catalog
		// bug rather than anything a generator run can recover from.
		panic(fmt.Sprintf("generate-artifact-catalog: no JSON Schema for value kind %q", schema.Kind))
	}
	return definition
}

func componentReferences(components []artifactdoc.ComponentName) []object {
	references := make([]object, 0, len(components))
	for _, name := range components {
		references = append(references, object{{key: "$ref", value: "#/$defs/" + string(name)}})
	}
	return references
}

// conformanceFixture is one accepted document together with the tree Setta's
// compiler produced for it.
type conformanceFixture struct {
	Name        string           `json:"name"`
	Description string           `json:"description"`
	Source      string           `json:"source"`
	Root        artifactdoc.Node `json:"root"`
}

func writeCorpus(outputDir string, catalog artifactdoc.Catalog) error {
	fixtures, err := compileCorpus(catalog)
	if err != nil {
		return err
	}
	if err := os.RemoveAll(outputDir); err != nil {
		return fmt.Errorf("remove generated corpus directory: %w", err)
	}
	if err := os.MkdirAll(outputDir, 0o755); err != nil {
		return fmt.Errorf("create generated corpus directory: %w", err)
	}
	if err := os.WriteFile(filepath.Join(outputDir, "types.ts"), renderCorpusTypes(), 0o644); err != nil {
		return fmt.Errorf("write corpus types module: %w", err)
	}
	imports := make([]string, 0, len(fixtures))
	bindings := make([]string, 0, len(fixtures))
	for index, fixture := range fixtures {
		fileName := fmt.Sprintf("%02d_%s", index, fixture.Name)
		binding := fmt.Sprintf("fixture%02d", index)
		source, err := renderCorpusFixture(fixture)
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(outputDir, fileName+".ts"), source, 0o644); err != nil {
			return fmt.Errorf("write corpus fixture %s: %w", fixture.Name, err)
		}
		imports = append(imports, fmt.Sprintf("import { artifactConformanceFixture as %s } from \"./%s\";\n", binding, fileName))
		bindings = append(bindings, binding)
	}
	if err := os.WriteFile(filepath.Join(outputDir, "index.ts"), renderCorpusIndex(imports, bindings), 0o644); err != nil {
		return fmt.Errorf("write corpus index module: %w", err)
	}
	return nil
}

func compileCorpus(catalog artifactdoc.Catalog) ([]conformanceFixture, error) {
	accepted := artifactdoc.AcceptedFixtures()
	fixtures := make([]conformanceFixture, 0, len(accepted))
	covered := make(map[artifactdoc.ComponentName]bool, len(catalog.Components))
	for _, fixture := range accepted {
		document, err := artifactdoc.Compile(catalog, fixture.Source)
		if err != nil {
			return nil, fmt.Errorf("compile accepted fixture %s: %w", fixture.Name, err)
		}
		observeComponents(document.Root, covered)
		fixtures = append(fixtures, conformanceFixture{
			Name:        fixture.Name,
			Description: fixture.Description,
			Source:      fixture.Source,
			Root:        document.Root,
		})
	}
	missing := make([]string, 0, len(catalog.Components))
	for _, name := range catalog.Names() {
		if !covered[name] {
			missing = append(missing, string(name))
		}
	}
	if len(missing) > 0 {
		return nil, fmt.Errorf("accepted corpus never renders %s", strings.Join(missing, ", "))
	}
	return fixtures, nil
}

func observeComponents(node artifactdoc.Node, covered map[artifactdoc.ComponentName]bool) {
	covered[node.Component] = true
	for _, value := range node.Props {
		observeValue(value, covered)
	}
}

func observeValue(value any, covered map[artifactdoc.ComponentName]bool) {
	switch typed := value.(type) {
	case artifactdoc.Node:
		observeComponents(typed, covered)
	case []any:
		for _, entry := range typed {
			observeValue(entry, covered)
		}
	case map[string]any:
		for _, entry := range typed {
			observeValue(entry, covered)
		}
	}
}

func renderCorpusTypes() []byte {
	var output bytes.Buffer
	output.WriteString(generatedHeader)
	output.WriteString("import type { ArtifactDocumentNode } from \"../artifact-catalog\";\n\n")
	output.WriteString("/**\n")
	output.WriteString(" * One document Setta's compiler accepted, carried with the tree it produced.\n")
	output.WriteString(" * The pinned upstream OpenUI parser has to reach the same tree from the same\n")
	output.WriteString(" * source before the production cutover may begin.\n")
	output.WriteString(" */\n")
	output.WriteString("export interface ArtifactConformanceFixture {\n")
	output.WriteString("  readonly name: string;\n")
	output.WriteString("  readonly description: string;\n")
	output.WriteString("  readonly source: string;\n")
	output.WriteString("  readonly root: ArtifactDocumentNode;\n")
	output.WriteString("}\n")
	return output.Bytes()
}

func renderCorpusFixture(fixture conformanceFixture) ([]byte, error) {
	payload, err := json.MarshalIndent(fixture, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("marshal corpus fixture %s: %w", fixture.Name, err)
	}
	var output bytes.Buffer
	output.WriteString(generatedHeader)
	output.WriteString("import type { ArtifactConformanceFixture } from \"./types\";\n\n")
	output.WriteString("export const artifactConformanceFixture: ArtifactConformanceFixture = ")
	output.Write(payload)
	output.WriteString(";\n")
	return output.Bytes(), nil
}

func renderCorpusIndex(imports []string, bindings []string) []byte {
	var output bytes.Buffer
	output.WriteString(generatedHeader)
	for _, statement := range imports {
		output.WriteString(statement)
	}
	output.WriteString("import type { ArtifactConformanceFixture } from \"./types\";\n\n")
	output.WriteString("export type { ArtifactConformanceFixture } from \"./types\";\n\n")
	output.WriteString("/** The accepted corpus, in the order the Go corpus declares it. */\n")
	output.WriteString("export const artifactConformanceFixtures: readonly ArtifactConformanceFixture[] = [\n")
	for _, binding := range bindings {
		fmt.Fprintf(&output, "  %s,\n", binding)
	}
	output.WriteString("];\n")
	return output.Bytes()
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
