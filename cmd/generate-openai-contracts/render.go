package main

import (
	"bytes"
	"fmt"
	"strconv"
)

func renderGoContracts(model generationModel) ([]byte, error) {
	createSpeech, err := operationNamed(model.Operations, "createSpeech")
	if err != nil {
		return nil, err
	}
	createRealtimeCall, err := operationNamed(model.Operations, model.Transcription.WebRTCOperation)
	if err != nil {
		return nil, err
	}
	createRealtimeClientSecret, err := operationNamed(model.Operations, "createRealtimeClientSecret")
	if err != nil {
		return nil, err
	}
	var output bytes.Buffer
	output.WriteString("// Code generated by go run ./cmd/generate-openai-contracts; DO NOT EDIT.\n\n")
	output.WriteString("package speech\n\n")
	output.WriteString("const (\n")
	writeGoStringConstant(&output, "openAIContractSourceCommit", model.SourceCommit)
	writeGoStringConstant(&output, "openAIContractAPIVersion", model.APIVersion)
	writeGoStringConstant(&output, "openAIBaseURL", model.ServerURL)
	writeGoOperationConstants(&output, "openAICreateSpeech", createSpeech)
	writeGoOperationConstants(&output, "openAICreateRealtimeCall", createRealtimeCall)
	writeGoOperationConstants(&output, "openAICreateRealtimeClientSecret", createRealtimeClientSecret)
	writeGoStringConstant(&output, "TranscriptionModel", model.Transcription.Model)
	writeGoStringConstant(&output, "TranscriptionDelay", model.Transcription.Delay)
	writeGoStringConstant(&output, "SynthesisModel", model.Speech.Model)
	writeGoStringConstant(&output, "SynthesisVoice", model.Speech.Voice)
	writeGoStringConstant(&output, "OpenAISynthesisResponseFormat", model.Speech.ResponseFormat)
	fmt.Fprintf(&output, "\trealtimeClientSecretTTLSeconds = %d\n", model.Transcription.ClientSecretTTLSeconds)
	fmt.Fprintf(&output, "\tMaximumSynthesisCharacters = %d\n", model.MaximumSynthesisCharacters)
	output.WriteString("\tOpenAIWebRTCURL = openAIBaseURL + openAICreateRealtimeCallPath\n")
	output.WriteString(")\n\n")
	output.WriteString("var (\n")
	writeGoStringArray(&output, "openAICreateSpeechWireResponseMediaTypes", createSpeech.WireResponseMediaTypes)
	writeGoStringArray(&output, "openAICreateRealtimeCallWireResponseMediaTypes", createRealtimeCall.WireResponseMediaTypes)
	writeGoStringArray(&output, "openAICreateRealtimeClientSecretWireResponseMediaTypes", createRealtimeClientSecret.WireResponseMediaTypes)
	output.WriteString(")\n")
	return output.Bytes(), nil
}

func writeGoOperationConstants(output *bytes.Buffer, prefix string, operation operationContract) {
	writeGoStringConstant(output, prefix+"Path", operation.Path)
	writeGoStringConstant(output, prefix+"RequestMediaType", operation.RequestMediaType)
	writeGoStringConstant(output, prefix+"ResponseMediaType", operation.ResponseMediaType)
}

func writeGoStringConstant(output *bytes.Buffer, name, value string) {
	fmt.Fprintf(output, "\t%s = %s\n", name, strconv.Quote(value))
}

func writeGoStringArray(output *bytes.Buffer, name string, values []string) {
	fmt.Fprintf(output, "\t%s = [...]string{", name)
	for index, value := range values {
		if index > 0 {
			output.WriteString(", ")
		}
		output.WriteString(strconv.Quote(value))
	}
	output.WriteString("}\n")
}

func renderTypeScriptContracts(model generationModel) []byte {
	var output bytes.Buffer
	output.WriteString("// Code generated by go run ./cmd/generate-openai-contracts; DO NOT EDIT.\n\n")
	fmt.Fprintf(&output, "export const openAIContractSourceCommit = %s as const;\n", quoteTypeScript(model.SourceCommit))
	fmt.Fprintf(&output, "export const openAIContractAPIVersion = %s as const;\n\n", quoteTypeScript(model.APIVersion))
	writeTypeScriptOperations(&output, model.Operations)
	writeTypeScriptClientEventTypes(&output, model.ClientEvents)
	writeTypeScriptEventTypes(&output, model.Events)
	output.WriteString("export type OpenAIRealtimeServerEventType =\n")
	output.WriteString("  (typeof openAIRealtimeServerEventType)[keyof typeof openAIRealtimeServerEventType];\n\n")
	output.WriteString("export type OpenAISchemaShape =\n")
	output.WriteString("  | \"array\"\n  | \"boolean\"\n  | \"integer\"\n  | \"null\"\n  | \"number\"\n  | \"object\"\n  | \"reference\"\n  | \"string\"\n  | \"union\"\n  | \"unknown\";\n\n")
	output.WriteString("interface OpenAIRealtimeServerEventContract {\n")
	output.WriteString("  properties: Readonly<Record<string, OpenAISchemaShape>>;\n")
	output.WriteString("  requiredFields: readonly string[];\n")
	output.WriteString("  schemaName: string;\n")
	output.WriteString("}\n\n")
	writeTypeScriptEventContracts(&output, model.Events)
	output.WriteString("export function isOpenAIRealtimeServerEventType(\n")
	output.WriteString("  value: string,\n")
	output.WriteString("): value is OpenAIRealtimeServerEventType {\n")
	output.WriteString("  return Object.prototype.hasOwnProperty.call(openAIRealtimeServerEventContracts, value);\n")
	output.WriteString("}\n")
	return output.Bytes()
}

func writeTypeScriptClientEventTypes(output *bytes.Buffer, events []realtimeEventContract) {
	output.WriteString("export const openAIRealtimeClientEventType = {\n")
	for _, event := range events {
		fmt.Fprintf(output, "  %s: %s,\n", event.Name, quoteTypeScript(event.Type))
	}
	output.WriteString("} as const;\n\n")
}

func writeTypeScriptOperations(output *bytes.Buffer, operations []operationContract) {
	output.WriteString("export const openAIOperations = {\n")
	for _, operation := range operations {
		fmt.Fprintf(output, "  %s: {\n", operation.Name)
		fmt.Fprintf(output, "    method: %s,\n", quoteTypeScript(operation.Method))
		fmt.Fprintf(output, "    operationId: %s,\n", quoteTypeScript(operation.OperationID))
		fmt.Fprintf(output, "    path: %s,\n", quoteTypeScript(operation.Path))
		fmt.Fprintf(output, "    requestMediaType: %s,\n", quoteTypeScript(operation.RequestMediaType))
		if operation.RequestSchema == "" {
			output.WriteString("    requestSchema: null,\n")
		} else {
			fmt.Fprintf(output, "    requestSchema: %s,\n", quoteTypeScript(operation.RequestSchema))
		}
		fmt.Fprintf(output, "    responseMediaType: %s,\n", quoteTypeScript(operation.ResponseMediaType))
		fmt.Fprintf(output, "    successStatus: %s,\n", quoteTypeScript(operation.SuccessStatus))
		output.WriteString("    wireResponseMediaTypes: [")
		for index, mediaType := range operation.WireResponseMediaTypes {
			if index > 0 {
				output.WriteString(", ")
			}
			output.WriteString(quoteTypeScript(mediaType))
		}
		output.WriteString("],\n")
		output.WriteString("  },\n")
	}
	output.WriteString("} as const;\n\n")
}

func writeTypeScriptEventTypes(output *bytes.Buffer, events []realtimeEventContract) {
	output.WriteString("export const openAIRealtimeServerEventType = {\n")
	for _, event := range events {
		fmt.Fprintf(output, "  %s: %s,\n", event.Name, quoteTypeScript(event.Type))
	}
	output.WriteString("} as const;\n\n")
}

func writeTypeScriptEventContracts(output *bytes.Buffer, events []realtimeEventContract) {
	output.WriteString("export const openAIRealtimeServerEventContracts = {\n")
	for _, event := range events {
		fmt.Fprintf(output, "  [openAIRealtimeServerEventType.%s]: {\n", event.Name)
		output.WriteString("    properties: {\n")
		for _, property := range event.Properties {
			fmt.Fprintf(output, "      %s: %s,\n", quoteTypeScript(property.Name), quoteTypeScript(property.Shape))
		}
		output.WriteString("    },\n")
		output.WriteString("    requiredFields: [")
		for index, field := range event.Required {
			if index > 0 {
				output.WriteString(", ")
			}
			output.WriteString(quoteTypeScript(field))
		}
		output.WriteString("],\n")
		fmt.Fprintf(output, "    schemaName: %s,\n", quoteTypeScript(event.Schema))
		output.WriteString("  },\n")
	}
	output.WriteString("} as const satisfies Record<\n")
	output.WriteString("  OpenAIRealtimeServerEventType,\n")
	output.WriteString("  OpenAIRealtimeServerEventContract\n")
	output.WriteString(">;\n\n")
}

func quoteTypeScript(value string) string {
	return strconv.Quote(value)
}
