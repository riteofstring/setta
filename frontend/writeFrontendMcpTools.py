#!/usr/bin/env python3
import json
import os
import sys
from datetime import datetime
from pathlib import Path

def generate_mcp_tools(json_path, output_path):
    """Generate MCP tool proxy functions from raw jsdoc output"""
    # Create directory if it doesn't exist
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    
    # Load raw jsdoc output
    with open(json_path, 'r') as f:
        raw_docs = json.load(f)
    
    # Generate Python code
    output = f'''"""
MCP Tool Proxy Functions
Generated automatically on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}
DO NOT EDIT THIS FILE MANUALLY
"""

from setta.mcp.server import mcp_server

'''
    
    # Group tools by source file for better organization
    tools_by_file = {}
    for doc in raw_docs:
        source_file = doc.get('meta', {}).get('filename', 'unknown')
        if source_file not in tools_by_file:
            tools_by_file[source_file] = []
        tools_by_file[source_file].append(doc)
    
    # Generate a proxy function for each tool, grouped by source file
    for source_file, docs in tools_by_file.items():
        rel_path = os.path.basename(source_file)
        output += f"\n# From {rel_path}\n"
        
        for doc in docs:
            # Extract parameters
            params = []
            param_docs = []
            for param in doc.get('params', []):
                name = param.get('name', '').replace('[', '').replace(']', '').split('=')[0].strip()
                type_str = '|'.join(param.get('type', {}).get('names', [])) if param.get('type') else 'any'
                description = param.get('description', '')
                required = not param.get('optional', False)
                default_value = param.get('defaultvalue')
                
                params.append({
                    'name': name,
                    'required': required,
                    'default': default_value
                })
                
                param_docs.append(f"        {name} ({type_str}): {description}")
            
            # Extract return info
            return_info = None
            if doc.get('returns') and len(doc['returns']) > 0:
                return_type = '|'.join(doc['returns'][0].get('type', {}).get('names', [])) if doc['returns'][0].get('type') else 'any'
                return_desc = doc['returns'][0].get('description', '')
                return_info = f"        {return_type}: {return_desc}"
            
            # Generate function
            func_name = doc.get('name', '')
            description = doc.get('description', '')
            
            # Function decorator
            output += '@mcp_server.tool(\n'
            output += f'    description="{description}"\n'
            output += ')\n'
            
            # Function signature
            signature_params = []
            for param in params:
                if param['required']:
                    signature_params.append(param['name'])
                elif param['default'] is not None:
                    signature_params.append(f"{param['name']}={param['default']}")
                else:
                    signature_params.append(f"{param['name']}=None")
            
            output += f"async def {func_name}({', '.join(signature_params)}):\n"
            
            # Docstring
            output += f'    """{description}\n'
            
            if param_docs:
                output += '\n    Parameters:\n'
                output += '\n'.join(f"    {p}" for p in param_docs)
            
            if return_info:
                output += '\n\n    Returns:\n'
                output += f"    {return_info}"
            
            output += '\n    """\n'
            
            # Function implementation
            if params:
                output += '    kwargs = {}\n'
                for param in params:
                    output += f'    kwargs["{param["name"]}"] = {param["name"]}\n'
                output += f'    return await mcp_server.setta_websocket.use_frontend_tool("{func_name}", **kwargs)\n'
            else:
                output += f'    return await mcp_server.setta_websocket.use_frontend_tool("{func_name}")\n'
            
            output += '\n'
    
    # Write to file
    with open(output_path, 'w') as f:
        f.write(output)
    
    print(f"Successfully generated MCP tools module at {output_path}")

if __name__ == "__main__":
    generate_mcp_tools("mcp-tools.json", "../backend/setta/mcp/tools.py")