"""Context propagation helpers for Setta log records."""

import contextvars
import logging
from collections.abc import Iterator, Mapping
from contextlib import contextmanager

from setta.logging.redaction import sanitize_for_logging_context, to_compact_json

LoggingContextPrimitive = str | int | float | bool
LoggingContextInput = object | None
LoggingContextData = dict[str, str]
LoggingContextToken = contextvars.Token[LoggingContextData]

_EMPTY_CONTEXT: LoggingContextData = {}
_LOGGING_CONTEXT_VAR: contextvars.ContextVar[LoggingContextData] = (
    contextvars.ContextVar("setta_logging_context", default=_EMPTY_CONTEXT)
)

__all__ = [
    "LoggingContextFilter",
    "LoggingContextInput",
    "LoggingContextPrimitive",
    "LoggingContextToken",
    "get_logging_context",
    "logging_context",
    "push_logging_context",
    "reset_logging_context",
]


def get_logging_context() -> LoggingContextData:
    """Return a copy of the current logging context."""

    context_data = _LOGGING_CONTEXT_VAR.get()
    if context_data is _EMPTY_CONTEXT:
        return {}
    return dict(context_data)


def push_logging_context(
    *,
    replace: bool = False,
    values: Mapping[str, LoggingContextInput] | None = None,
    **kwargs: LoggingContextInput,
) -> LoggingContextToken:
    """Merge new context values into the current context.

    When `replace` is True, the provided values replace the current context
    rather than merging into it.
    """

    merged_values: dict[str, LoggingContextInput] = {}
    if values:
        merged_values.update(values)
    if kwargs:
        merged_values.update(kwargs)
    if replace:
        new_context = _normalize_mapping(merged_values)
    else:
        new_context = _updated_context(merged_values)
    return _LOGGING_CONTEXT_VAR.set(new_context)


def reset_logging_context(token: LoggingContextToken) -> None:
    """Reset the logging context to a previous token."""

    _LOGGING_CONTEXT_VAR.reset(token)


@contextmanager
def logging_context(
    *,
    values: Mapping[str, LoggingContextInput] | None = None,
    **kwargs: LoggingContextInput,
) -> Iterator[None]:
    """Context manager that temporarily updates the logging context."""

    token = push_logging_context(values=values, **kwargs)
    try:
        yield
    finally:
        reset_logging_context(token)


class LoggingContextFilter(logging.Filter):
    """Attach context metadata to each log record."""

    def filter(self, record: logging.LogRecord) -> bool:  # noqa: D401 (generated by logging)
        context_data = get_logging_context()
        if context_data:
            for key, value in context_data.items():
                if hasattr(record, key):
                    continue
                setattr(record, key, value)
            record.setta_context = _format_context(context_data)
        else:
            record.setta_context = "-"
        return True


def _format_context(context_data: Mapping[str, str]) -> str:
    pairs = [f"{key}={value}" for key, value in sorted(context_data.items())]
    return " ".join(pairs)


def _updated_context(
    updates: Mapping[str, LoggingContextInput],
) -> LoggingContextData:
    base = get_logging_context()
    if not updates:
        return base
    for key, value in updates.items():
        if value is None:
            base.pop(key, None)
            continue
        base[key] = _normalize_value(value)
    return base


def _normalize_mapping(
    mapping: Mapping[str, LoggingContextInput],
) -> LoggingContextData:
    normalized: LoggingContextData = {}
    for key, value in mapping.items():
        if value is None:
            continue
        normalized[key] = _normalize_value(value)
    return normalized


def _normalize_value(value: LoggingContextInput) -> str:
    if value is None:
        raise ValueError("logging context values cannot be None")
    if isinstance(value, bool):
        return "true" if value else "false"
    sanitized = sanitize_for_logging_context(value)
    if sanitized is None:
        raise ValueError("logging context values cannot be None")
    if isinstance(sanitized, bool):
        return "true" if sanitized else "false"
    if isinstance(sanitized, (int, float)):
        return str(sanitized)
    if isinstance(sanitized, str):
        return sanitized
    return to_compact_json(sanitized)
