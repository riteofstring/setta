"""Context propagation helpers for Setta log records."""

import contextvars
import dataclasses
import logging
import re
from collections.abc import Iterator
from contextlib import contextmanager
from types import MappingProxyType

from setta.logging.redaction import sanitize_for_logging_context, to_compact_json

LoggingContextPrimitive = str | int | float | bool
LoggingContextInput = object | None
LoggingContextData = dict[str, str]
LoggingContextToken = contextvars.Token["_LoggingContextSnapshot"]


@dataclasses.dataclass(frozen=True, slots=True)
class _LoggingContextSnapshot:
    data: MappingProxyType[str, str]
    setta_context: str


_EMPTY_SNAPSHOT = _LoggingContextSnapshot(MappingProxyType({}), "-")
_LOGGING_CONTEXT_VAR: contextvars.ContextVar[_LoggingContextSnapshot] = (
    contextvars.ContextVar("setta_logging_context", default=_EMPTY_SNAPSHOT)
)

__all__ = [
    "LoggingContextFilter",
    "LoggingContextInput",
    "LoggingContextPrimitive",
    "LoggingContextToken",
    "get_logging_context",
    "logging_context",
    "push_logging_context",
    "reset_logging_context",
]


def get_logging_context() -> LoggingContextData:
    """Return a copy of the current logging context."""

    return dict(_LOGGING_CONTEXT_VAR.get().data)


def push_logging_context(
    *,
    replace: bool = False,
    values: dict[str, LoggingContextInput] | None = None,
    **kwargs: LoggingContextInput,
) -> LoggingContextToken:
    """Merge new context values into the current context.

    When `replace=True`, the current context is discarded and replaced entirely with
    the provided values (or cleared when no values are provided).
    """

    merged_values: dict[str, LoggingContextInput] = {}
    if values:
        merged_values.update(values)
    if kwargs:
        merged_values.update(kwargs)
    new_values = _updated_context(merged_values, replace=replace)
    snapshot = _build_snapshot(new_values)
    return _LOGGING_CONTEXT_VAR.set(snapshot)


def reset_logging_context(token: LoggingContextToken) -> None:
    """Reset the logging context to a previous token."""
    try:
        _LOGGING_CONTEXT_VAR.reset(token)
    except ValueError:
        # Contextvars tokens must be reset in the same logical context they were
        # created in. During interpreter/task teardown (notably in pytest), the
        # generator owning this context can be finalized in a different context.
        # In that case the original context is already gone, so best-effort clear
        # is enough and avoiding unraisable teardown warnings is more valuable.
        _LOGGING_CONTEXT_VAR.set(_EMPTY_SNAPSHOT)


@contextmanager
def logging_context(
    *,
    replace: bool = False,
    values: dict[str, LoggingContextInput] | None = None,
    **kwargs: LoggingContextInput,
) -> Iterator[None]:
    """Context manager that temporarily updates the logging context."""

    token = push_logging_context(replace=replace, values=values, **kwargs)
    try:
        yield
    finally:
        reset_logging_context(token)


class LoggingContextFilter(logging.Filter):
    """Attach context metadata to each log record."""

    def filter(self, record: logging.LogRecord) -> bool:  # noqa: D401 (generated by logging)
        record.setta_context = _LOGGING_CONTEXT_VAR.get().setta_context
        return True


def _updated_context(
    updates: dict[str, LoggingContextInput],
    *,
    replace: bool,
) -> LoggingContextData:
    base = {} if replace else dict(_LOGGING_CONTEXT_VAR.get().data)
    if not updates:
        return base
    for key, value in updates.items():
        if value is None:
            base.pop(key, None)
            continue
        base[key] = _normalize_value(value)
    return base


def _normalize_value(value: LoggingContextInput) -> str:
    if value is None:
        raise ValueError("logging context values cannot be None")
    if isinstance(value, bool):
        return "true" if value else "false"
    sanitized = sanitize_for_logging_context(value)
    if sanitized is None:
        raise ValueError("logging context values cannot be None")
    if isinstance(sanitized, bool):
        return "true" if sanitized else "false"
    if isinstance(sanitized, (int, float)):
        return str(sanitized)
    if isinstance(sanitized, str):
        return sanitized
    return to_compact_json(sanitized)


def _build_snapshot(values: LoggingContextData) -> _LoggingContextSnapshot:
    if not values:
        return _EMPTY_SNAPSHOT
    return _LoggingContextSnapshot(
        data=MappingProxyType(values),
        setta_context=_format_context_string(values),
    )


def _format_context_string(values: LoggingContextData) -> str:
    pairs = [
        f"{key}={_format_logfmt_value(value)}" for key, value in sorted(values.items())
    ]
    return " ".join(pairs)


_LOGFMT_SAFE_VALUE_RE = re.compile(r"^[A-Za-z0-9_./:@+-]+$")


def _format_logfmt_value(value: str) -> str:
    if value == "":
        return '""'
    if _LOGFMT_SAFE_VALUE_RE.fullmatch(value):
        return value
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'
